static int gpuCores() {
  // (the number of GPU cores: IOKit's gpu-core-count; an estimate from the working set where it is not readable)
  static int cores = [] {
    int c = 0;
    if (const char* e = getenv("LOCALFOLD_GPU_CORES")) c = atoi(e);
    if (!c) {
      FILE* p = popen("ioreg -rc AGXAccelerator -d1 2>/dev/null | grep -o '\"gpu-core-count\" = [0-9]*' | grep -o '[0-9]*$'", "r");
      if (p) { if (fscanf(p, "%d", &c) != 1) c = 0; pclose(p); }
    }
    return c > 0 ? c : 8;
  }();
  return cores;
}
cudaError_t cudaDeviceGetAttribute(int* v, cudaDeviceAttr a, int) {
  switch (a) {
    case cudaDevAttrMultiProcessorCount: *v = gpuCores(); break;
    // (a T4's - sm_75: the ports' register-staged paths, no cp.async, no bf16 tensor-core GEMMs)
    case cudaDevAttrComputeCapabilityMajor: *v = 7; break;
    case cudaDevAttrComputeCapabilityMinor: *v = 5; break;
    case cudaDevAttrMaxSharedMemoryPerBlockOptin:
    case cudaDevAttrMaxSharedMemoryPerBlock: *v = (int)R().dev.maxThreadgroupMemoryLength; break;
    case cudaDevAttrMaxSharedMemoryPerMultiprocessor: *v = 65536; break;
    case cudaDevAttrMaxThreadsPerBlock: *v = 1024; break;
    case cudaDevAttrL2CacheSize: *v = 8 << 20; break;
    default: *v = 0;
  }
  return cudaSuccess;
}
