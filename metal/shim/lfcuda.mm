namespace lf {
void setLaunchRaw(dim3 grid, dim3 block, size_t smem) { CURRENT = {grid, block, smem}; }
void launch(int index, std::initializer_list<std::string> targs, KArgs& args) {
  Runtime& r = R();
  std::lock_guard<std::recursive_mutex> l(r.mu);
  std::string ta;
  for (auto& t : targs) ta += (ta.empty() ? "" : ", ") + t;
  if (ta.empty()) ta = "0";
  id<MTLComputePipelineState> pso = r.kernel(index, ta);
  Launch L = CURRENT;
  // (an overridden kernel lays out its own threadgroup memory within the device's: the host asked for the CUDA layout)
  if (PORT_KERNELS[index].status == 1) L.smem = std::min<size_t>(L.smem, r.dev.maxThreadgroupMemoryLength - pso.staticThreadgroupMemoryLength);
  size_t threads = (size_t)L.block.x * L.block.y * L.block.z;
  if (threads > pso.maxTotalThreadsPerThreadgroup)
    die(std::string("kernel ") + PORT_KERNELS[index].name + "<" + ta + "> launched with " + std::to_string(threads) +
        " threads a block; this GPU runs it with at most " + std::to_string(pso.maxTotalThreadsPerThreadgroup));
  if (pso.staticThreadgroupMemoryLength + L.smem > r.dev.maxThreadgroupMemoryLength)
    die(std::string("kernel ") + PORT_KERNELS[index].name + "<" + ta + "> needs " +
        std::to_string(pso.staticThreadgroupMemoryLength + L.smem) + " bytes of threadgroup memory; this GPU has " +
        std::to_string(r.dev.maxThreadgroupMemoryLength));
  r.dispatch(pso, args.bytes.data(), args.bytes.size(), MTLSizeMake(L.grid.x, L.grid.y, L.grid.z),
             MTLSizeMake(L.block.x, L.block.y, L.block.z), L.smem, r.profiling ? std::string(PORT_KERNELS[index].name) : "");
}
void* hostView(const void* device) { return R().host(device); }
void profileStart() {
  Runtime& r = R(); r.sync(); r.profile.clear(); r.profiled.clear(); r.profiling = true;
}
void profileStop(int top) {
  Runtime& r = R(); r.sync(); r.profiling = false;
  double total = 0;
  for (auto& [name, c] : r.profiled) {
    double ms = (c.GPUEndTime - c.GPUStartTime) * 1e3;
    r.profile[name].first += ms; r.profile[name].second += 1; total += ms;
  }
  std::vector<std::pair<std::string, std::pair<double, int>>> rows(r.profile.begin(), r.profile.end());
  std::sort(rows.begin(), rows.end(), [](auto& a, auto& b) { return a.second.first > b.second.first; });
  printf("profile: %.1f ms of GPU time in %zu dispatches (each its own command buffer: an upper bound)\n", total, r.profiled.size());
  for (int i = 0; i < (int)rows.size() && i < top; ++i)
    printf("  %8.2f ms %5.1f%% %6d  %s\n", rows[i].second.first, 100 * rows[i].second.first / std::max(total, 1e-9),
           rows[i].second.second, rows[i].first.c_str());
  r.profiled.clear();
}
