// The CUDA runtime, cuBLAS and cuBLASLt on Metal (declared in lfcuda.h).
//
// Memory: every allocation is one shared MTLBuffer and its device pointer is the buffer's GPU address, so the
// ports' pointer arithmetic, structs of pointers and arrays of pointers all hold as they are. Unified memory
// makes the same bytes the host's, through the buffer's contents.
//
// Order: every stream is the one queue, and every dispatch goes into the current compute encoder, which runs its
// dispatches serially - CUDA's stream order. A device-to-host copy waits for the queue; a host-to-device copy
// writes in place when the queue is idle and otherwise stages its bytes and copies them in order on the GPU.
//
// Kernels: the port's translated source (cu2metal.py) compiled from source, one explicit instantiation per
// specialisation a launch asks for. Specialisations seen before (a cache beside the weights) are compiled together
// up front; a new one costs a compile of its own and is remembered.
