cudaError_t lfSymbolAddress(void** p, const void* host, size_t bytes) {
  static std::map<const void*, void*> copies;
  Runtime& r = R();
  std::lock_guard<std::recursive_mutex> l(r.mu);
  auto it = copies.find(host);
  if (it == copies.end()) {
    void* d = r.malloc_(bytes);
    r.sync();
    memcpy(r.host(d), host, bytes);
    it = copies.emplace(host, d).first;
  }
  *p = it->second;
  return cudaSuccess;
}

