namespace {
const char* typeTag(cudaDataType t) {
  switch (t) {
    case CUDA_R_32F: return "f32";
    case CUDA_R_16F: return "f16";
    case CUDA_R_16BF: return "bf16";
    default: die("a GEMM of an unsupported data type " + std::to_string((int)t));
  }
}
struct GemmArgs {
  uint64_t A, B, C, D, bias;
  int64_t sa, sb, sc, sd;
  int32_t m, n, k, lda, ldb, ldc, ldd;
  int32_t ta, tb, ptrs, epilogue, biasType;
  float alpha, beta;
};
void gemm(cudaDataType ta_, cudaDataType tb_, cudaDataType tc_, GemmArgs a, int batch) {
  if (a.m <= 0 || a.n <= 0 || batch <= 0) return;
  Runtime& r = R();
  std::lock_guard<std::recursive_mutex> l(r.mu);
  std::string name = std::string("lf_gemm_") + typeTag(ta_) + "_" + typeTag(tb_) + "_" + typeTag(tc_);
  MTLSize grid = MTLSizeMake((a.m + 63) / 64, (a.n + 63) / 64, batch);
  r.dispatch(r.shimPipeline(name), &a, sizeof a, grid, MTLSizeMake(128, 1, 1), 0, r.profiling ? "gemm" : "");
}
float scalar(const void* p, cublasComputeType_t compute) {
  if (compute == CUBLAS_COMPUTE_16F) return (float)*(const __half*)p;
  return *(const float*)p;
}
}  // namespace

