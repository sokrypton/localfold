cudaError_t cudaMalloc(void** p, size_t bytes) {
  *p = R().malloc_(bytes);
  return *p ? cudaSuccess : (LAST_ERROR = cudaErrorMemoryAllocation);
}
cudaError_t cudaFree(void* p) { R().free_(p); return cudaSuccess; }
cudaError_t cudaMallocAsync(void** p, size_t bytes, cudaStream_t) { return cudaMalloc(p, bytes); }
