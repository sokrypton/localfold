}
cudaError_t cudaEventElapsedTime(float* ms, cudaEvent_t a, cudaEvent_t b) {
  cudaEventSynchronize(a); cudaEventSynchronize(b);
  // (the GPU's end of the work before each: the time the queue took between them)
  double ta = a->cb ? a->cb.GPUEndTime : a->host, tb = b->cb ? b->cb.GPUEndTime : b->host;
  if (!a->cb || !b->cb) { ta = a->host; tb = b->host; }
  *ms = (float)((tb - ta) * 1e3);
  if (*ms < 0) *ms = 0;
  return cudaSuccess;
}
