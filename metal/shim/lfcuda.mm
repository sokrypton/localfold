cudaError_t cudaMallocHost(void** p, size_t bytes) {
  *p = nullptr;
  return posix_memalign(p, 16384, std::max<size_t>(bytes, 1)) == 0 ? cudaSuccess : cudaErrorMemoryAllocation;
}
