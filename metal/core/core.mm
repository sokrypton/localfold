int GEMM_EXTRA_EP = 0;
namespace {
// The matrix units' GEMM (gemm_tensor.metal): half operands, any output, every epilogue. LOCALFOLD_GEMM_TENSOR=0 keeps
// lf_gemm (the control); read at every call, as the bench's arms set it.
bool tensorWanted() {
  const char* e = getenv("LOCALFOLD_GEMM_TENSOR");
  return D().tensorOps && !(e && !strcmp(e, "0"));
}
void gemmTensorRun(DT tc_, GemmArgs a, int batch, bool accFloat, const char* label) {
  static const bool floatAcc = getenv("LOCALFOLD_GEMM_FLOAT_ACC") && strcmp(getenv("LOCALFOLD_GEMM_FLOAT_ACC"), "0") != 0;
  // a half output takes a half destination even where the caller asked for float accumulation: the matrix units sum a
  // whole run wider than half and round once on the way out (6MRR's and 5CAJ's folds unchanged to the PDB's 0.001 A;
  // 512 x 65025 x 128 with a bias 0.86 ms against 1.41 into a float destination - the float tile's register cost)
  const bool hacc = !floatAcc && tc_ == F16;
  const bool tri = a.epilogue & 256;
  const bool plain = !tri && (a.epilogue & ~6) == 0 && a.alpha == 1.f && a.beta == 0.f;
  // the tile: TM rows along n by TN columns along m. A short n (up to 128) in one tile row, rounded up to 16, 64 columns
  // where the weight is wide enough to fill the GPU (3072 x 80 x 768: 0.064 ms at 80 x 64 against 0.078 at 80 x 128) and
  // 32 where not (768 x 80 x 768: 0.062 against 0.075); a taller n 64 x 128 (512 x 68121 x 128 half: 0.93 ms against
  // 1.20 at 64 x 64; 4096 square 12.0 TFLOP/s against 9.5). Measured on an M5 (8-core GPU), interleaved.
  int tm = a.n <= 128 ? (a.n + 15) / 16 * 16 : 64, tn = a.n <= 128 ? (a.m >= 40 * 64 ? 64 : 32) : (a.m >= 128 ? 128 : 64);
  if (const char* t = getenv("LOCALFOLD_GEMM_TILE")) sscanf(t, "%dx%d", &tm, &tn);
  const bool triReg = tri && (a.epilogue & 512);
  if (triReg) { tm = 64; tn = 128; }      // (the layout lf_tri_quarters wrote: 32 channels a tile)
  // the general epilogues in registers, 4 columns at a time (LOCALFOLD_GEMM_VEC=0 the control): where the tile is
  // 64 rows and everything the epilogue touches is 4-element aligned
  static const bool vecWanted = !getenv("LOCALFOLD_GEMM_VEC") || atoi(getenv("LOCALFOLD_GEMM_VEC")) != 0;
  auto al4 = [](uint64_t p, int64_t ld) { return p % 16 == 0 && ld % 4 == 0; };
  const bool vecEp = vecWanted && !plain && !tri && !(a.epilogue & (128 | 256)) && tm == 64 && a.m % 4 == 0 && !a.ptrs &&
                     al4(a.D, a.ldd) && al4(a.D + 0, a.sd) && (a.beta == 0.f && !(a.epilogue & 64) ? true : al4(a.C, a.ldc) && al4(a.C, a.sc)) &&
                     (!(a.epilogue & 64) || al4(a.aux, a.ldaux)) && (!(a.epilogue & 4) || a.bias % 16 == 0);
  if (vecEp && tn < 64) tn = 64;
  // (a staged epilogue holds the tile in threadgroup memory: 32 KB on Apple's GPUs, some of it the operation's own)
  while (!plain && !tri && !vecEp && tm * tn * (hacc ? 2 : 4) > 16384 && tn > 16) tn /= 2;
  if (tri && tn % 32) die("gemm: the triangle gate wants a tile 32 columns wide or more, not %d", tn);
  if (tm % 16 || tn % 16 || tm < 16 || tn < 16) die("gemm: no %d x %d tensor tile", tm, tn);
  const int ep = (tri ? 1 : 0) | (plain ? 2 : 0) | (hacc ? 8 : 0) | (triReg ? 16 : 0) | (vecEp ? 128 : 0);
  const char* tcs = tc_ == F32 ? "float" : "half";
  std::string targs = std::string("half, half, ") + tcs + ", " + std::to_string(tm) + ", " + std::to_string(tn) + ", " +
                      (a.ta ? "true" : "false") + ", " + (a.tb ? "true" : "false") + ", " + std::to_string(ep);
  std::string name = std::string("gemmt_hh") + (tc_ == F32 ? "f" : "h") + "_" + std::to_string(tm) + "x" + std::to_string(tn) +
                     "_" + (a.ta ? "T" : "N") + (a.tb ? "T" : "N") + "_e" + std::to_string(ep);
  std::string decl = "template [[host_name(\"" + name + "\")]] kernel void lf_gemm_tensor<" + targs + ">(constant GemmArgs&, uint3, uint);";
  Grid grid{(uint32_t)((a.m + tn - 1) / tn), (uint32_t)((a.n + tm - 1) / tm), (uint32_t)batch};
  std::string lab;
  if (D().profileOn) {
    char b[160]; snprintf(b, sizeof b, "%s %s %dx%dx%d%s", label ? label : "gemm", name.c_str() + 6, a.m, a.n, a.k, batch > 1 ? " batched" : "");
    lab = b;
  }
  dispatchInstance(name, decl, &a, sizeof a, grid, 128, 0, lab.empty() ? nullptr : lab.c_str());
}
void gemmRun(DT ta_, DT tb_, DT tc_, GemmArgs a, int batch, bool halfMma, bool accFloat, const char* label) {
  if (a.m <= 0 || a.n <= 0 || batch <= 0) return;
  ++D().stats.gemms;
  if (ta_ == F16 && tb_ == F16 && tensorWanted()) { gemmTensorRun(tc_, a, batch, accFloat, label); return; }
  // the tile: TR rows along n by TC columns along m. A short n (up to 128) in ONE tile row - every weight read once -
  // rounded up to 16; the columns then as many as keep a simdgroup's accumulators at 16 or fewer
  int tr = 64, tc = 64;
  // (80 rows take 64 columns too where there are 40 tiles of them: a simdgroup's 40 x 32 reloads fewer fragments a
  // multiply - 0.187 against 0.254 ms on 3072 x 80 x 768, 1.70 against 2.00 on 73728 x 80 x 384, interleaved - and
  // narrower weights keep 32, whose extra threadgroups win there: 0.102 against 0.118 ms on 768 x 80 x 768)
  if (a.n <= 128) { tr = (a.n + 15) / 16 * 16; tc = tr <= 64 || (tr <= 80 && a.m >= 40 * 64) ? 64 : 32; }
  else if (a.m <= 48) { tr = 64; tc = 32; }
  // 48-row tiles where 64 would waste over a tenth of the rows on padding and 48 wastes less
  if (a.n > 128 && tr == 64) {
    long pad64 = (long)((a.n + 63) / 64) * 64 - a.n, pad48 = (long)((a.n + 47) / 48) * 48 - a.n;
    if (pad64 * 10 > a.n && pad48 < pad64) tr = 48;
  }
  auto groups = [&](int c) { return (long)((a.m + c - 1) / c) * ((a.n + tr - 1) / tr) * batch; };
  while (tc > 16 && groups(tc) < 64) tc /= 2;
  // ...and 48-column tiles likewise (not SwiGLU's or the triangle gate's, whose epilogues pair 8-column blocks)
  if (tc == 64 && !(a.epilogue & (128 | 256))) {
    long pad64 = (long)((a.m + 63) / 64) * 64 - a.m, pad48 = (long)((a.m + 47) / 48) * 48 - a.m;
    if (pad64 * 10 > a.m && pad48 < pad64) tc = 48;
  }
  if ((a.epilogue & 128) && tc < 32) tc = 32;
  if (a.epilogue & 256) tc = 64;
  if (const char* t = getenv("LOCALFOLD_GEMM_TILE")) sscanf(t, "%dx%d", &tr, &tc);
  if (tr % 16 || tc % 16 || tr < 16 || tc < 16) die("gemm: no %d x %d tile", tr, tc);
  auto esize = [](DT t) { return t == F32 ? 4 : 2; };
  bool vec = !a.ptrs && a.lda % 8 == 0 && a.ldb % 8 == 0 && a.sa % 8 == 0 && a.sb % 8 == 0 &&
             a.A % (8 * esize(ta_)) == 0 && a.B % (8 * esize(tb_)) == 0;
  if (vec) a.biasType |= 256;
  int bk = (tc >= 48 && tr >= 48) || (tc == 32 && tr >= 80) ? 16 : 32;
  if (const char* e = getenv("LOCALFOLD_GEMM_BK")) bk = atoi(e);
  static const bool floatAcc = getenv("LOCALFOLD_GEMM_FLOAT_ACC") && strcmp(getenv("LOCALFOLD_GEMM_FLOAT_ACC"), "0") != 0;
  const bool hacc = !floatAcc && !accFloat && ta_ == F16 && tb_ == F16 && tc_ == F16;
  const bool hmma = halfMma && !(ta_ == F16 && tb_ == F16);     // (half staging of an f32 operand)
  auto mtype = [](DT t) { return t == F32 ? "float" : "half"; };
  int ep = (a.epilogue & 256 ? 1 : 0) | (hacc ? 8 : 0) | (hmma ? 32 : 0) | GEMM_EXTRA_EP;
  std::string targs = std::string(mtype(ta_)) + ", " + mtype(tb_) + ", " + mtype(tc_) + ", " + std::to_string(tr) + ", " +
                      std::to_string(tc) + ", " + (a.ta ? "true" : "false") + ", " + (a.tb ? "true" : "false") + ", " +
                      std::to_string(bk) + ", " + std::to_string(ep);
  auto tag = [](DT t) { return t == F32 ? "f" : "h"; };
  std::string name = std::string("gemm_") + tag(ta_) + tag(tb_) + tag(tc_) + "_" + std::to_string(tr) + "x" + std::to_string(tc) +
                     "_" + (a.ta ? "T" : "N") + (a.tb ? "T" : "N") + "_k" + std::to_string(bk) + "_e" + std::to_string(ep);
  std::string decl = "template [[host_name(\"" + name + "\")]] kernel void lf_gemm<" + targs + ">(constant GemmArgs&, uint3, uint, uint, uint);";
  Grid grid{(uint32_t)((a.m + tc - 1) / tc), (uint32_t)((a.n + tr - 1) / tr), (uint32_t)batch};
  std::string lab;
  if (D().profileOn) {
    char b[160]; snprintf(b, sizeof b, "%s %s %dx%dx%d%s", label ? label : "gemm", name.c_str() + 5, a.m, a.n, a.k, batch > 1 ? " batched" : "");
    lab = b;
  }
  dispatchInstance(name, decl, &a, sizeof a, grid, 128, 0, lab.empty() ? nullptr : lab.c_str());
}
