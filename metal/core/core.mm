void die(const char* fmt, ...) {
  va_list ap; va_start(ap, fmt);
  fprintf(stderr, "localfold-metal: ");
  vfprintf(stderr, fmt, ap);
  fprintf(stderr, "\n");
  va_end(ap);
  fflush(stderr);
  std::exit(1);
}

namespace {
struct Alloc { id<MTLBuffer> buf; uint64_t addr; size_t size; };
struct Stats { double syncMs = 0, compileMs = 0; long dispatches = 0, commits = 0, syncs = 0, staged = 0, allocs = 0, gemms = 0; };

struct Device {
  std::recursive_mutex mu;
  id<MTLDevice> dev;
  id<MTLCommandQueue> queue;
  std::map<uint64_t, Alloc> allocs;
  size_t held = 0, peak = 0, buried = 0, peakLive = 0;     // (live: held and the graveyard's, still resident)
  id<MTLCommandBuffer> cb = nil;
  id<MTLComputeCommandEncoder> enc = nil;
  std::vector<id<MTLBuffer>> keep;           // staged and argument buffers, alive until this command buffer is done
  // released buffers, each alive until every command buffer committed up to its tag is done (Metal may complete a
  // later command buffer before an earlier one it sees no dependency on)
  std::vector<std::pair<long, id<MTLBuffer>>> graveyard;
  int encoded = 0;
  std::mutex inflightMu; std::condition_variable inflightDone; std::set<long> pending; long committedSeq = 0;
  std::mutex errorMu; std::string gpuError;
  // kernels
  std::string portName = "core";
  const char* portSource = nullptr;
  id<MTLLibrary> lib = nil;
  std::mutex libMu;
  std::unordered_map<std::string, id<MTLComputePipelineState>> pipelines;
  std::set<std::string> knownSpecs; std::string specsPath; bool specsLoaded = false;
  std::map<std::string, std::string> specDecls;
  // the matrix units through Metal 4's tensor operations (gemm_tensor.metal): an Apple10 GPU (M5) on macOS 26
  bool tensorOps = false;
  // profiling
  bool profileOn = false;
  std::vector<std::pair<std::string, id<MTLCommandBuffer>>> profiled;
  Stats stats;
  // scratch
  std::map<std::string, std::pair<void*, size_t>> scratch;

  Device() {
    @autoreleasepool {
      NSArray<id<MTLDevice>>* devices = MTLCopyAllDevices();
      if (devices.count == 0) die("no Metal device");
      dev = devices[0];
      if (![dev supportsFamily:MTLGPUFamilyMetal3] || ![dev supportsFamily:MTLGPUFamilyApple7])
        die("this GPU (%s) is not an Apple-silicon GPU with Metal 3; LocalFold needs an M1 or later", dev.name.UTF8String);
      queue = [dev newCommandQueueWithMaxCommandBufferCount:64];
      if (@available(macOS 26.0, *)) tensorOps = [dev supportsFamily:MTLGPUFamilyApple10];
    }
  }

  // ---- memory
  const Alloc* find(uint64_t addr) {
    auto it = allocs.upper_bound(addr);
    if (it == allocs.begin()) return nullptr;
    --it;
    if (addr >= it->second.addr && addr < it->second.addr + std::max<size_t>(it->second.size, 1)) return &it->second;
    return nullptr;
  }
  void* alloc(size_t bytes) {
    std::lock_guard<std::recursive_mutex> l(mu);
    size_t n = std::max<size_t>((bytes + 255) & ~(size_t)255, 256);
    // released buffers the work in flight may still read are kept until it is done; past a bound, wait for it rather
    // than hold both (a 522-token trunk pass held 0.9 GB of them beside its own 1.9). LOCALFOLD_BURIED_MB: the bound
    static const size_t bound = (size_t)(getenv("LOCALFOLD_BURIED_MB") ? atof(getenv("LOCALFOLD_BURIED_MB")) : 128) << 20;
    if (buried >= bound) sync();
    id<MTLBuffer> b = [dev newBufferWithLength:n options:MTLResourceStorageModeShared];
    if (!b) die("out of memory: %.2f GB asked for with %.2f GB held", bytes / 1e9, held / 1e9);
    ++stats.allocs;
    uint64_t addr = b.gpuAddress;
    allocs[addr] = {b, addr, n};
    held += n; peak = std::max(peak, held); peakLive = std::max(peakLive, held + buried);
    if (enc) [enc useResource:b usage:MTLResourceUsageRead | MTLResourceUsageWrite];
    return (void*)addr;
  }
  void release(const void* p) {
    if (!p) return;
    std::lock_guard<std::recursive_mutex> l(mu);
    static const bool syncRelease = getenv("LOCALFOLD_SYNC_RELEASE") != nullptr;    // (debugging: lifetimes)
    if (syncRelease) sync();
    auto it = allocs.find((uint64_t)p);
    if (it == allocs.end()) die("release of a pointer that is not an allocation's start");
    held -= it->second.size;
    if (!idle()) { graveyard.push_back({committedSeq + (cb ? 1 : 0), it->second.buf}); buried += it->second.size; }   // (work issued may read it)
    allocs.erase(it);
  }
  void* host(const void* p, size_t bytes = 0) {
    const Alloc* a = find((uint64_t)p);
    if (!a) die("not a device pointer: %p", p);
    if ((uint64_t)p + bytes > a->addr + a->size) die("a host access past the end of its allocation");
    return (char*)a->buf.contents + ((uint64_t)p - a->addr);
  }

  // ---- the queue
  bool idle() { std::lock_guard<std::mutex> g(inflightMu); return !cb && pending.empty(); }
  void ensureEncoder() {
    if (enc) return;
    if (!cb) cb = [queue commandBufferWithUnretainedReferences];
    enc = [cb computeCommandEncoderWithDispatchType:MTLDispatchTypeSerial];
    std::vector<id<MTLResource>> all;
    all.reserve(allocs.size() + keep.size());
    for (auto& [_, a] : allocs) all.push_back(a.buf);
    for (auto& b : keep) all.push_back(b);
    // (not the graveyard's: released buffers are read by no new work, and one named resident by a command buffer still in
    // flight when the graveyard frees it is an "Invalid Resource" failure of that command buffer, though it never reads it)
    if (!all.empty()) [enc useResources:all.data() count:all.size() usage:MTLResourceUsageRead | MTLResourceUsageWrite];
  }
  void commit() {
    if (enc) { [enc endEncoding]; enc = nil; }
    if (!cb) return;
    if (!keep.empty()) {
      __block std::vector<id<MTLBuffer>> k = std::move(keep);
      keep.clear();
      [cb addCompletedHandler:^(id<MTLCommandBuffer>) { k.clear(); }];
    }
    long seq;
    { std::lock_guard<std::mutex> g(inflightMu); seq = ++committedSeq; pending.insert(seq); }
    [cb addCompletedHandler:^(id<MTLCommandBuffer> done) {
      if (done.error) {
        std::lock_guard<std::mutex> g(errorMu);
        if (gpuError.empty()) gpuError = done.error.localizedDescription.UTF8String;
      }
      { std::lock_guard<std::mutex> g(inflightMu); pending.erase(seq); }
      inflightDone.notify_all();
    }];
    [cb commit];
    ++stats.commits;
    bury();
    cb = nil;
    encoded = 0;
  }
  void bury() {               // the released buffers no command buffer in flight can read
    if (graveyard.empty()) return;
    long oldest;
    { std::lock_guard<std::mutex> g(inflightMu); oldest = pending.empty() ? LONG_MAX : *pending.begin(); }
    graveyard.erase(std::remove_if(graveyard.begin(), graveyard.end(), [&](auto& e) {
      if (e.first >= oldest) return false;
      buried -= e.second.length;
      return true;
    }), graveyard.end());
  }
  void sync() {
    std::lock_guard<std::recursive_mutex> l(mu);
    commit();
    ++stats.syncs;
    auto t0 = std::chrono::steady_clock::now();
    { std::unique_lock<std::mutex> g(inflightMu); inflightDone.wait(g, [&] { return pending.empty(); }); }
    stats.syncMs += std::chrono::duration<double, std::milli>(std::chrono::steady_clock::now() - t0).count();
    bury();
    std::lock_guard<std::mutex> g(errorMu);
    if (!gpuError.empty()) die("the GPU failed: %s", gpuError.c_str());
  }

  // ---- kernels
  id<MTLLibrary> compile(const std::string& source, const std::string& what, bool tensor = false) {
    MTLCompileOptions* o = [MTLCompileOptions new];
    o.languageVersion = MTLLanguageVersion3_0;
    if (tensor) {
      if (@available(macOS 26.0, *)) o.languageVersion = MTLLanguageVersion4_0;
      else die("compiling %s: the tensor GEMM needs macOS 26", what.c_str());
    }
    o.fastMathEnabled = NO;
    NSError* e = nil;
    auto t0 = std::chrono::steady_clock::now();
    id<MTLLibrary> l = [dev newLibraryWithSource:[NSString stringWithUTF8String:source.c_str()] options:o error:&e];
    stats.compileMs += std::chrono::duration<double, std::milli>(std::chrono::steady_clock::now() - t0).count();
    if (!l) die("compiling %s:\n%s", what.c_str(), e ? e.localizedDescription.UTF8String : "?");
    return l;
  }
  id<MTLComputePipelineState> pipelineOf(id<MTLLibrary> l, const std::string& name) {
    id<MTLFunction> f = [l newFunctionWithName:[NSString stringWithUTF8String:name.c_str()]];
    if (!f) die("no kernel %s", name.c_str());
    NSError* e = nil;
    id<MTLComputePipelineState> p = [dev newComputePipelineStateWithFunction:f error:&e];
    if (!p) die("%s: %s", name.c_str(), e ? e.localizedDescription.UTF8String : "?");
    return p;
  }
  id<MTLLibrary> portLib() {
    std::lock_guard<std::mutex> g(libMu);
    if (!lib) {
      if (!portSource) die("no kernel source (setSource)");
      lib = compile(portSource, "the " + portName + " kernels");
    }
    return lib;
  }
  // the pipelines by name (pipeMu: the precompiling thread inserts beside the encoding one)
  std::mutex pipeMu, specMu;
  std::shared_future<void> precompiling;
  id<MTLComputePipelineState> cached(const std::string& name) {
    std::lock_guard<std::mutex> g(pipeMu);
    auto it = pipelines.find(name);
    return it == pipelines.end() ? nil : it->second;
  }
  void remember(const std::string& name, id<MTLComputePipelineState> p) { std::lock_guard<std::mutex> g(pipeMu); pipelines[name] = p; }
  id<MTLComputePipelineState> kernel(const char* name) {
    if (id<MTLComputePipelineState> p = cached(name)) return p;
    id<MTLComputePipelineState> p = pipelineOf(portLib(), name);
    remember(name, p);
    return p;
  }
  std::string cacheDir() {
    const char* home = getenv("HOME");
    std::string base = std::string(home ? home : "/tmp") + "/.cache";
    mkdir(base.c_str(), 0755); mkdir((base + "/localfold").c_str(), 0755); mkdir((base + "/localfold/metal").c_str(), 0755);
    return base + "/localfold/metal";
  }
  void loadSpecs() {      // (specMu held)
    if (specsLoaded) return;
    specsLoaded = true;
    std::string name = "/" + specsName(portName.c_str());
    specsPath = cacheDir() + name;
    struct stat st;
    if (stat(specsPath.c_str(), &st) != 0) {     // a first run: the list a wheel ships beside the binary
      char exe[4096]; uint32_t size = sizeof exe;
      if (_NSGetExecutablePath(exe, &size) == 0) {
        std::string bundled = std::string(exe);
        bundled = bundled.substr(0, bundled.rfind('/')) + "/metal-specs" + name;
        std::ifstream src(bundled);
        if (src) { std::ofstream dst(specsPath); dst << src.rdbuf(); }
      }
    }
    std::ifstream in(specsPath);
    std::string line;
    while (std::getline(in, line)) {
      size_t tab = line.find('\t');
      if (tab == std::string::npos) continue;
      knownSpecs.insert(line.substr(0, tab));
      specDecls[line.substr(0, tab)] = line.substr(tab + 1);
    }
  }
  // every instance a previous run used, compiled on threads of their own while the caller loads weights - in parallel
  // chunks, the compiler being single-threaded
  void precompile() {
    std::vector<std::pair<std::string, std::string>> todo;
    {
      std::lock_guard<std::mutex> g(specMu);
      loadSpecs();
      for (auto& [n, d] : specDecls) if (!cached(n)) todo.push_back({n, d});
    }
    if (todo.empty()) return;
    precompiling = std::async(std::launch::async, [this, todo] {
      // (the tensor instances in libraries of their own: another source, another language version - and none on a GPU
      // without the units, where a cached list from an M5 names them)
      std::vector<std::pair<std::string, std::string>> groups[2];
      for (auto& t : todo) if (!isTensor(t.first)) groups[0].push_back(t); else if (tensorOps) groups[1].push_back(t);
      std::vector<std::thread> threads;
      for (int tensor = 0; tensor < 2; ++tensor) {
        const std::vector<std::pair<std::string, std::string>>* list = &groups[tensor];   // (groups outlives the threads)
        const size_t chunks = std::min<size_t>(tensor ? 4 : 8, (list->size() + 7) / 8);
        for (size_t c = 0; c < chunks; ++c)
          threads.emplace_back([this, list, chunks, c, tensor] { @autoreleasepool {
            std::string src = tensor ? TENSOR_SOURCE : GEMM_SOURCE;
            for (size_t i = c; i < list->size(); i += chunks) src += "\n" + (*list)[i].second;
            id<MTLLibrary> l = compile(src, "the cached instances", tensor);
            for (size_t i = c; i < list->size(); i += chunks) remember((*list)[i].first, pipelineOf(l, (*list)[i].first));
          } });
      }
      for (auto& t : threads) t.join();
    }).share();
  }
  static bool isTensor(const std::string& name) { return name.compare(0, 6, "gemmt_") == 0; }
  id<MTLComputePipelineState> instance(const std::string& name, const std::string& decl) {
    if (id<MTLComputePipelineState> p = cached(name)) return p;
    if (precompiling.valid()) { precompiling.wait(); if (id<MTLComputePipelineState> p = cached(name)) return p; }
    auto t0 = std::chrono::steady_clock::now();
    const bool tensor = isTensor(name);
    id<MTLComputePipelineState> p = pipelineOf(compile(std::string(tensor ? TENSOR_SOURCE : GEMM_SOURCE) + "\n" + decl + "\n", name, tensor), name);
    if (getenv("LOCALFOLD_METAL_VERBOSE"))
      fprintf(stderr, "metal: compiled %s in %.0f ms\n", name.c_str(),
              std::chrono::duration<double, std::milli>(std::chrono::steady_clock::now() - t0).count());
    remember(name, p);
    std::lock_guard<std::mutex> g(specMu);
    loadSpecs();
    if (!knownSpecs.count(name)) {
      knownSpecs.insert(name); specDecls[name] = decl;
      std::ofstream out(specsPath, std::ios::app);
      out << name << "\t" << decl << "\n";
    }
    return p;
  }
  void dispatch(id<MTLComputePipelineState> pso, const void* args, size_t argBytes, Grid g, uint32_t threads, size_t smem,
                const char* label) {
    if (!g.x || !g.y || !g.z) return;
    if (threads > pso.maxTotalThreadsPerThreadgroup)
      die("a dispatch of %u threads a threadgroup to a kernel that takes at most %lu (%s)", threads,
          (unsigned long)pso.maxTotalThreadsPerThreadgroup, label ? label : "?");
    // LOCALFOLD_CHECK_ARGS=1: every 8-byte word of the arguments that points into a RELEASED buffer is a use after
    // release (debugging: the graveyard keeps it alive only until the work issued before the release is done)
    static const bool checkArgs = getenv("LOCALFOLD_CHECK_ARGS") != nullptr;
    if (checkArgs)
      for (size_t o = 0; o + 8 <= argBytes; o += 8) {
        uint64_t v; memcpy(&v, (const char*)args + o, 8);
        for (auto& [tag, b] : graveyard)
          if (v >= b.gpuAddress && v < b.gpuAddress + b.length)
            die("%s: argument word %zu points into a released buffer (%lu bytes)", label ? label : "?", o / 8, (unsigned long)b.length);
      }
    ensureEncoder();
    ++stats.dispatches;
    [enc setComputePipelineState:pso];
    if (argBytes <= 4096) [enc setBytes:args length:std::max<size_t>(argBytes, 4) atIndex:0];
    else {
      id<MTLBuffer> b = [dev newBufferWithBytes:args length:argBytes options:MTLResourceStorageModeShared];
      keep.push_back(b);
      [enc useResource:b usage:MTLResourceUsageRead];
      [enc setBuffer:b offset:0 atIndex:0];
    }
    if (smem) [enc setThreadgroupMemoryLength:(smem + 15) & ~(size_t)15 atIndex:0];
    [enc dispatchThreadgroups:MTLSizeMake(g.x, g.y, g.z) threadsPerThreadgroup:MTLSizeMake(threads, 1, 1)];
    // LOCALFOLD_SYNC_EACH=1: every dispatch waited for and checked, a failure named by its kernel (debugging)
    static const bool syncEach = getenv("LOCALFOLD_SYNC_EACH") != nullptr;
    if (syncEach) {
      id<MTLCommandBuffer> mine = cb;
      commit();
      [mine waitUntilCompleted];
      if (mine.error) die("the GPU failed in %s: %s", label ? label : "?", mine.error.localizedDescription.UTF8String);
      return;
    }
    static const bool commitEach = getenv("LOCALFOLD_COMMIT_EACH") != nullptr;
    if (commitEach) {                       // (each its own command buffer, unwaited: a failure named by its kernel)
      std::string lab = label ? label : "?";
      [cb addCompletedHandler:^(id<MTLCommandBuffer> done) {
        if (done.error) fprintf(stderr, "the GPU failed in %s: %s\n", lab.c_str(), done.error.localizedDescription.UTF8String);
      }];
      commit();
      return;
    }
    if (profileOn && label) {               // (a command buffer a dispatch: its GPU time is the kernel's)
      id<MTLCommandBuffer> mine = cb;
      commit();
      profiled.push_back({label, mine});
    } else if (++encoded >= 128) {
      commit();                             // (let the GPU start while the host encodes the rest)
    }
  }
};
Device& D() { static Device* d = new Device(); return *d; }
}  // namespace

