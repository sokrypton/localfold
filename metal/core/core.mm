void gemm(const Gemm& g) {
  if (!g.rows || !g.out || g.batch <= 0) return;
  GemmArgs a{};
  a.A = (uint64_t)g.W; a.B = (uint64_t)g.X; a.C = (uint64_t)(g.Yin ? g.Yin : g.Y); a.D = (uint64_t)g.Y;
  a.m = g.out; a.n = (int)g.rows; a.k = g.in;
  a.lda = g.ldw ? g.ldw : (g.transW ? g.in : g.out);
  a.ldb = g.ldx ? g.ldx : (g.transX ? (int)g.rows : g.in);
  a.ldc = a.ldd = g.ldy ? g.ldy : g.out;
  a.ta = g.transW; a.tb = g.transX;
  a.sa = g.sw; a.sb = g.sx; a.sc = a.sd = g.sy;
  a.alpha = g.alpha; a.beta = g.beta;
  if (g.bias) { a.bias = (uint64_t)g.bias; a.epilogue |= 4; a.biasType = g.tbias == F16 ? 2 : 0; }
  if (g.relu) a.epilogue |= 2;
  if (g.gelu) a.epilogue |= 32;
  gemmRun(g.tw, g.tx, g.ty, a, g.batch, g.half, g.accFloat, g.label);
}
void gemmGatedAdd(const half* X, const half* W, const half* aux, float* pair, size_t rows, int in, int out, const float* bias) {
  GemmArgs a{};
  a.A = (uint64_t)W; a.B = (uint64_t)X; a.C = a.D = (uint64_t)pair;
  a.m = out; a.n = (int)rows; a.k = in; a.lda = out; a.ldb = in; a.ldc = a.ldd = out;
  a.epilogue = 64; a.alpha = 1.f;
  a.aux = (uint64_t)aux; a.ldaux = out;
  if (bias) { a.bias = (uint64_t)bias; a.epilogue |= 4; }
  gemmRun(F16, F16, F32, a, 1, false, false, "gated add");
}
void gemmSwiglu(const half* X, const half* Wpairs, half* gated, size_t rows, int in, int hidden) {
  if (hidden % 8) die("gemmSwiglu: a hidden width of %d is not a multiple of 8", hidden);
  GemmArgs a{};
  a.A = (uint64_t)Wpairs; a.B = (uint64_t)X; a.C = a.D = (uint64_t)gated;
  a.m = 2 * hidden; a.n = (int)rows; a.k = in; a.lda = 2 * hidden; a.ldb = in; a.ldc = a.ldd = hidden;
  a.epilogue = 128; a.alpha = 1.f;
  gemmRun(F16, F16, F16, a, 1, false, false, "swiglu");
}
void gemmTriGate(const half* X, const half* W, const float* mask, half* outA, half* outB, size_t r0, size_t rows, int C,
                 size_t pairs, int n, int np, const float* bias) {
  GemmArgs g{};
  g.A = (uint64_t)W; g.B = (uint64_t)X; g.C = g.D = (uint64_t)outA;
  g.m = 4 * C; g.n = (int)rows; g.k = C; g.lda = 4 * C; g.ldb = C; g.ldc = g.ldd = 4 * C;
  g.epilogue = 256; g.alpha = 1.f;
  g.aux = (uint64_t)mask; g.aux2 = (uint64_t)outA; g.aux3 = (uint64_t)outB;
  g.tgR0 = (int64_t)r0; g.tgPairs = (int64_t)pairs; g.tgN = n; g.tgNp = np; g.tgC = C;
  if (bias) { g.bias = (uint64_t)bias; g.epilogue |= 4; }
  // on the matrix units the weight in quarters (lf_tri_quarters, every call into one buffer - 0.01 ms, and no cache
  // keyed by an address a later model's weights may reuse) and the gate in registers (epilogue 512): no staging tile.
  // LOCALFOLD_TRI_REG=0 the control
  static const bool reg = !getenv("LOCALFOLD_TRI_REG") || atoi(getenv("LOCALFOLD_TRI_REG")) != 0;
  if (reg && C % 32 == 0 && tensorWanted()) {
    static half* qw = nullptr; static float* qb = nullptr; static size_t qC = 0;
    if ((size_t)C > qC) { qw = allocT<half>((size_t)C * 4 * C); qb = allocT<float>((size_t)4 * C); qC = C; }
    run1d("lf_tri_quarters", (size_t)C * 4 * C, TriQuartersArgs{W, qw, bias, bias ? qb : nullptr, (uint64_t)C, (uint)C, 0});
    g.A = (uint64_t)qw;
    if (bias) g.bias = (uint64_t)qb;
    g.epilogue |= 512;
  }
  gemmRun(F16, F16, F16, g, 1, false, false, "triangle gate");
}

// ---------------------------------------------------------------- attention
// The matrix units' kernels (gemm_tensor.metal) where they win: lf_attention_tensor3 (v3: the online softmax in
// registers, no threadgroup memory) from 48 keys; lf_attention_tensor (v1) where there is a q bias, from 168 keys.
// Measured on an M5 (8-core GPU), interleaved, H 4 x n rows, lf_attention / v2 / v3 ms:
// n 255 D 32 3.86 / 1.87 / 1.63, D 64 6.83 / 3.15 / 2.90, D 16 2.50 / 1.69 / 1.61; n 384 D 32 x 128 rows 4.31 / 1.93
// / 1.58; n 128 D 32 0.53 / 0.30 / 0.26; n 64 D 32 0.093 / 0.077 / 0.074; n 48 D 32 0.227 / 0.216 / 0.118; but n 32
// D 32 0.032 / 0.038 / 0.035 - lf_attention's registers below 48. (v1 against those: n 255 D 32 3.06, n 128 0.47.)
// The key tile 64 unless that leaves the last one half empty or less, and 32 at D 16 (n 255: 1.61 against 1.74)
static const int ATTN_TENSOR_MIN_N = 168;
void attention(const Attention& t) {
  if (!t.rows || !t.n) return;
  int W = t.heads * t.D;
  AttnArgs a{};
  a.qkvg = t.qkvg; a.out = t.out; a.bias = t.bias; a.mask = t.mask; a.qBias = t.qBias;
  a.posStride = t.posStride ? t.posStride : 4 * W;
  a.rowStride = t.rowStride ? t.rowStride : (int64_t)t.n * a.posStride;
  a.outPosStride = t.outPosStride ? t.outPosStride : W;
  a.outRowStride = t.outRowStride ? t.outRowStride : (int64_t)t.n * a.outPosStride;
  a.r0 = t.r0; a.n = t.n; a.heads = t.heads; a.biasStride = t.biasStride; a.scale = t.scale;
  a.maskB = t.maskB || t.maskK ? t.maskB : t.n; a.maskK = t.maskB || t.maskK ? t.maskK : 1;
  a.pad0 = GEMM_EXTRA_EP;      // (an experiment's switch: metal/bench)
  // LOCALFOLD_ATTN_TENSOR=0 keeps lf_attention, =1 takes a tensor kernel at any length (the bench's arms);
  // LOCALFOLD_ATTN_V2=0 keeps v1 where v3 would run, =1 v2, =3 v3 at any length; LOCALFOLD_ATTN_TILE=QxK the tile
  if (D().tensorOps && (t.D == 16 || t.D == 32 || t.D == 48 || t.D == 64)) {
    const char* e = getenv("LOCALFOLD_ATTN_TENSOR");
    const char* v2 = getenv("LOCALFOLD_ATTN_V2");
    // the version: LOCALFOLD_ATTN_V2 unset - v3 from 48 keys (where the tensor kernels are on); 0 - v1; 1 or 2 - v2
    // (no q bias: v1 there); 3 - v3
    const int mode = v2 ? atoi(v2) : -1;
    const bool tensorOn = !e || strcmp(e, "0") != 0;
    int ver = mode < 0 ? (tensorOn && t.n >= 48 ? 3 : 1) : mode == 0 ? 1 : mode < 3 ? 2 : 3;
    if (ver == 2 && t.qBias) ver = 1;
    const bool two = ver > 1;
    const bool on = e ? strcmp(e, "0") != 0 : two || (t.n >= ATTN_TENSOR_MIN_N && t.D >= 32);
    if (on) {
      int TQB = 64, TKT = 32;
      if (two) { TQB = 16; TKT = (t.n % 64 == 0 || t.n % 64 > 32) && !(ver == 3 && t.D == 16) ? 64 : 32; }   // (v2's first number: queries a simdgroup)
      if (const char* tt = getenv("LOCALFOLD_ATTN_TILE")) sscanf(tt, "%dx%d", &TQB, &TKT);
      const char* stem = ver == 3 ? (t.qBias ? "gemmt_attn3q_" : "gemmt_attn3_") : ver == 2 ? "gemmt_attn2_" : "gemmt_attn_";
      const char* fn = ver == 3 ? "lf_attention_tensor3<" : ver == 2 ? "lf_attention_tensor2<" : "lf_attention_tensor<";
      std::string name = std::string(stem) + std::to_string(t.D) + "_" + std::to_string(TQB) + "x" + std::to_string(TKT);
      std::string decl = "template [[host_name(\"" + name + "\")]] kernel void " + fn +
                         std::to_string(t.D) + ", " + std::to_string(TQB) + ", " + std::to_string(TKT) +
                         (ver == 3 ? (t.qBias ? ", true" : ", false") : "") + ">(constant AttnArgs&, uint3, uint, uint, uint);";
      const int qb = two ? 4 * TQB : TQB;
      dispatchInstance(name, decl, &a, sizeof a, Grid{(uint32_t)((t.n + qb - 1) / qb), (uint32_t)t.rows, (uint32_t)t.heads}, 128, 0,
                       "attention");
      return;
    }
  }
  const char* k = t.D == 8 ? "lf_attention_8" : t.D == 16 ? "lf_attention_16" : t.D == 24 ? "lf_attention_24" : t.D == 32 ? "lf_attention_32"
                : t.D == 48 ? "lf_attention_48" : t.D == 64 ? "lf_attention_64" : nullptr;
  if (!k) die("attention: no kernel for a head %d wide", t.D);
  if (t.rows > 65535 * 64) die("attention: %zu rows", t.rows);
  const int QB = 32;
  dispatch(k, &a, sizeof a, Grid{(uint32_t)((t.n + QB - 1) / QB), (uint32_t)t.rows, (uint32_t)t.heads}, 128, 0, "attention");
}

