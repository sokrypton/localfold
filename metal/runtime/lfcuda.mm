void gemmCheck(cudaDataType ta_, cudaDataType tb_, cudaDataType tc_, const GemmArgs& a, int batch, const std::vector<unsigned char>& cBefore);
void gemm(cudaDataType ta_, cudaDataType tb_, cudaDataType tc_, GemmArgs a, int batch) {
  if (a.m <= 0 || a.n <= 0 || batch <= 0) return;
  Runtime& r = R();
  std::lock_guard<std::recursive_mutex> l(r.mu);
  // LOCALFOLD_CHECK_GEMM=<calls>: the first calls recomputed on the host (sampled entries, double) and compared
  static int checks = getenv("LOCALFOLD_CHECK_GEMM") ? atoi(getenv("LOCALFOLD_CHECK_GEMM")) : 0;
  bool check = checks > 0 && !r.capturingHere() && (!a.ptrs || a.beta == 0.f) && !(a.epilogue & (64 | 128 | 256));
  std::vector<unsigned char> cBefore;
  if (check) {
    --checks;
    r.sync();
    size_t es = tc_ == CUDA_R_32F ? 4 : 2;
    size_t span = ((size_t)(batch - 1) * a.sc + (size_t)(a.n - 1) * a.ldc + a.m) * es;
    cBefore.resize(span);
    if (a.beta != 0.f) memcpy(cBefore.data(), r.host((void*)a.C), span);
  }
  struct Run { cudaDataType ta_, tb_, tc_; GemmArgs a; int batch; bool check; std::vector<unsigned char>* cb; Runtime& r;
    ~Run() { if (check) { r.sync(); gemmCheck(ta_, tb_, tc_, a, batch, *cb); } } } run{ta_, tb_, tc_, a, batch, check, &cBefore, r};
  ++r.stats.gemms;
  // the tile: 64 x 64, or narrower along a short side (more threadgroups for a skinny product)
  // the tile: TR rows along n by TC columns along m. A short n (up to 128) in ONE tile row - every weight read once -
  // rounded up to 16; the columns then as many as keep a simdgroup's accumulators at 16 or fewer (TR/16 x TC/16)
  int tr = 64, tc = 64;
  if (a.n <= 128) {
    tr = (a.n + 15) / 16 * 16;
    tc = tr <= 64 ? 64 : 32;
  } else if (a.m <= 48) {
    tr = 64; tc = 32;
  }
  // a 48-row tile where 64-row tiles would waste over a tenth of the rows on padding and 48 wastes less: 272 rows (AF3's
  // diffusion at 255 tokens) are 320 in 64s and 288 in 48s - 0.91-0.96x the time there, 0.87x at 140 rows, and neutral
  // where it does not apply. An 80-row tile lost (1.06-1.16x at 4624 rows), and so did 48 for a 2% saving (1000 rows)
  if (a.n > 128 && tr == 64) {
    long pad64 = (long)((a.n + 63) / 64) * 64 - a.n, pad48 = (long)((a.n + 47) / 48) * 48 - a.n;
    if (pad64 * 10 > a.n && pad48 < pad64) tr = 48;
  }
  // too few threadgroups for the device: narrower columns
  auto groups = [&](int c) { return (long)((a.m + c - 1) / c) * ((a.n + tr - 1) / tr) * batch; };
  while (tc > 16 && groups(tc) < 64) tc /= 2;
  int bm = tc, bn = tr;
  auto esize = [](cudaDataType t) { return t == CUDA_R_32F ? 4 : 2; };
  bool vec = !a.ptrs && a.lda % 8 == 0 && a.ldb % 8 == 0 && (a.sa % 8 == 0) && (a.sb % 8 == 0) &&
             a.A % (8 * esize(ta_)) == 0 && a.B % (8 * esize(tb_)) == 0;
  if (vec) a.biasType |= 256;
  if (getenv("LF_GEMM_DEBUG")) fprintf(stderr, "gemm %dx%dx%d ta %d tb %d tile %dx%d vec %d batch %d\n", a.m, a.n, a.k, a.ta, a.tb, tr, tc, (int)vec, batch);
  auto mtype = [](cudaDataType t) { return t == CUDA_R_32F ? "float" : t == CUDA_R_16F ? "half" : "lf_bf16s"; };
  // the k step: 16 for a whole 64 x 64 tile, 32 otherwise. Measured interleaved (AB=1 metal/tools/bench-gemm) on an M2:
  // 16 is 0.73-0.85x the time on the triangle's tall K-128 projections (512 x 68121 x 128), 0.83-0.89x on the pair
  // track's 2048 x 4624 x 256 and 256 x 4624 x 1024, 0.84x on a 4096-cube - half the threadgroup memory, more tiles
  // resident to hide the loads - and 1.09x on a 64 x 32 tile, 1.08-1.21x on the 16-column ones
  int bk = tc == 64 && tr >= 48 ? 16 : 32;
  if (const char* k = getenv("LOCALFOLD_GEMM_BK")) bk = atoi(k) == 16 ? 16 : 32;       // (an arm: 16 or 32 everywhere)
  // an all-half GEMM accumulates in half: 0.85x the time on the trunk's K-128 projections (512, 128 and 1024 x 68121 x
  // 128, interleaved on an M2) for a relRMS of 1.7e-3 against 2.4e-4 - bfloat16's rounding, the precision AF3 runs at.
  // Accumulating each k step in half and adding it to a float accumulator (6.6e-4) won nothing. A GEMM writing float
  // (a residual) keeps float. LOCALFOLD_GEMM_FLOAT_ACC=1 is the control arm.
  static const bool floatAcc = getenv("LOCALFOLD_GEMM_FLOAT_ACC") != nullptr;
  // (not a float output, even at k <= 128: 0.94x on the residual's GEMMs, and IntelliFold-2 and ESMFold2 overflowed
  // one of them to inf and crashed downstream)
  const bool hacc = !floatAcc && ta_ == CUDA_R_16F && tb_ == CUDA_R_16F && tc_ == CUDA_R_16F;
  std::string targs = std::string(mtype(ta_)) + ", " + mtype(tb_) + ", " + mtype(tc_) + ", " + std::to_string(tr) + ", " +
                      std::to_string(tc) + ", " + (a.ta ? "true" : "false") + ", " + (a.tb ? "true" : "false") + ", " + std::to_string(bk) + ", " + std::to_string((a.epilogue & 256 ? 1 : 0) | (hacc ? 8 : 0));
  std::string name = std::string("lf_gemm_") + typeTag(ta_) + "_" + typeTag(tb_) + "_" + typeTag(tc_) + "_" +
                     std::to_string(tr) + "x" + std::to_string(tc) + "_" + (a.ta ? "T" : "N") + (a.tb ? "T" : "N") + (bk == 32 ? "" : "_k" + std::to_string(bk)) + (a.epilogue & 256 ? "_trigate" : "") + (hacc ? "_h" : "");
  if (getenv("LF_GEMM_DEBUG")) fprintf(stderr, "  -> %s\n", name.c_str());
  std::string decl = "template [[host_name(\"" + name + "\")]] kernel void lf_gemm<" + targs + ">(constant GemmArgs&, uint3, uint, uint, uint);";
  MTLSize grid = MTLSizeMake((a.m + bm - 1) / bm, (a.n + bn - 1) / bn, batch);
  char label[96]; snprintf(label, sizeof label, "gemm %s %dx%dx%d%s", name.c_str() + 8, a.m, a.n, a.k, batch > 1 ? " batched" : "");
  r.dispatch(r.runtimeInstance(name, decl), &a, sizeof a, grid, MTLSizeMake(128, 1, 1), 0, (r.profiling || r.capturingHere()) ? std::string(label) : "");
}
}  // namespace
// pair[r][o] += aux[r][o] * sigmoid(sum_k X[r][k] W[k][o]): a gate's GEMM adding its gated product into an f32 residual in
// its own epilogue, where cuBLAS's ports write the gate and add it in a pass of their own (metal/af3/patch)
void lf::gemmGatedAdd(const void* X, const void* W, const void* aux, float* pair, size_t rows, int in, int out) {
  GemmArgs a{(uint64_t)W, (uint64_t)X, (uint64_t)pair, (uint64_t)pair, 0, 0, 0, 0, 0, out, (int)rows, in, out, in, out, out,
             0, 0, 0, 64, 0, 1.f, 0.f};
  a.aux = (uint64_t)aux; a.ldaux = out;
  gemm(CUDA_R_16F, CUDA_R_16F, CUDA_R_32F, a, 1);
}
// gated[r][k] = silu(a) b, (a, b) = (X W)[r][2k, 2k+1]: W's columns interleaved a_0 b_0 a_1 b_1 ... (metal/af3/patch)
void lf::gemmSwiglu(const void* X, const void* Wpairs, void* gated, size_t rows, int in, int hidden) {
  GemmArgs a{(uint64_t)Wpairs, (uint64_t)X, (uint64_t)gated, (uint64_t)gated, 0, 0, 0, 0, 0, 2 * hidden, (int)rows, in,
             2 * hidden, in, hidden, hidden, 0, 0, 0, 128, 0, 1.f, 0.f};
  gemm(CUDA_R_16F, CUDA_R_16F, CUDA_R_16F, a, 1);
}
// the triangle's projection and gate in one GEMM: a[c][q], b[c][q] (channel-major over the padded positions) from
// X [rows][C] and W [C][4C] with channel c's (pa, pb, ga, gb) at columns 4c..4c+3 (metal/af3/pairtrack.cuh.patch)
void lf::gemmTriGate(const void* X, const void* W, const float* mask, void* a, void* b, size_t r0, size_t rows, int C,
                     size_t pairs, int n, int np) {
  GemmArgs g{(uint64_t)W, (uint64_t)X, (uint64_t)a, (uint64_t)a, 0, 0, 0, 0, 0, 4 * C, (int)rows, C, 4 * C, C, 4 * C,
             4 * C, 0, 0, 0, 256, 0, 1.f, 0.f};
  g.aux = (uint64_t)mask; g.aux2 = (uint64_t)a; g.aux3 = (uint64_t)b;
  g.tgR0 = (int64_t)r0; g.tgPairs = (int64_t)pairs; g.tgN = n; g.tgNp = np; g.tgC = C;
  gemm(CUDA_R_16F, CUDA_R_16F, CUDA_R_16F, g, 1);
}
