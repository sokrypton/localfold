namespace {
[[noreturn]] void die(const std::string& what) {
  fprintf(stderr, "localfold-metal: %s\n", what.c_str());
  fflush(stderr);
  std::exit(1);
}

struct Alloc { id<MTLBuffer> buf; uint64_t addr; size_t size; };

struct Op {        // a captured graph's step
  int kind;        // 0 dispatch, 1 copy, 2 fill
  id<MTLComputePipelineState> pso; std::vector<unsigned char> args; MTLSize grid, block; size_t smem;
  uint64_t dst, src; size_t bytes; int value;
  std::vector<id<MTLBuffer>> keep;
  std::string label;
};

struct Runtime {
  std::recursive_mutex mu;
  id<MTLDevice> dev;
  id<MTLCommandQueue> queue;
  id<MTLLibrary> runtimeLib;
  std::map<uint64_t, Alloc> allocs;
  size_t allocated = 0, peak = 0;
  id<MTLCommandBuffer> cb = nil;
  id<MTLComputeCommandEncoder> enc = nil;
  std::vector<id<MTLBuffer>> cbKeep;           // released when the command buffer is done
  id<MTLCommandBuffer> lastCommitted = nil;
  int encoded = 0, encodedInEncoder = 0;
  // a graph capture belongs to the thread that began it (cudaStreamCaptureModeThreadLocal, the mode every port uses):
  // another thread's work - a weight upload beside a warm-up - runs as it is, not into that thread's graph. It was
  // global, so an upload issued during the warm-up sampler's capture went into the graph and its event records were
  // dropped, and the decode buffer they guarded was overwritten before its decode ran: ESMFold2's folding weights
  // came out wrong a few times in a hundred (1QYS 13.5 A or NaN against 0.865), under load or on a slow first run
  bool captureActive = false; std::thread::id captureThread;
  bool capturingHere() const { return captureActive && std::this_thread::get_id() == captureThread; }
  // the command buffers committed and not yet complete, by commit order (their completion handlers remove them)
  std::mutex inflightMu; std::condition_variable inflightDone; std::set<long> pending; long committedSeq = 0;
  std::mutex gpuErrorMu; std::string gpuError;   // the first command buffer to fail (commit's completion handler)
  std::vector<Op>* capture = nullptr;
  std::unordered_map<std::string, id<MTLComputePipelineState>> pipelines;
  std::map<std::string, id<MTLComputePipelineState>> runtimePipelines;
  std::set<std::string> knownSpecs;
  std::string specsPath;
  bool specsLoaded = false;
  // LOCALFOLD_METAL_STATS: where the host's time goes (printed at exit)
  struct Stats { double launchMs = 0, syncMs = 0, compileMs = 0; long launches = 0, syncs = 0, staged = 0, encoders = 0,
                 directCopies = 0, commits = 0, allocs = 0, commitsThreshold = 0, commitsEvent = 0, idleChecks = 0, graphLaunches = 0, graphOps = 0, dispatches = 0, captures = 0, capturedOps = 0, copies = 0, fills = 0, gemms = 0, memsetCalls = 0, memcpyCalls = 0; } stats;
  bool statsOn = getenv("LOCALFOLD_METAL_STATS") != nullptr;
  bool untracked = getenv("LF_UNTRACKED") != nullptr;
  // profiling: GPU time per kernel name
  bool profiling = false;
  std::map<std::string, std::pair<double, int>> profile;
  std::vector<std::pair<std::string, id<MTLCommandBuffer>>> profiled;

  Runtime() {
    @autoreleasepool {
      NSArray<id<MTLDevice>>* devices = MTLCopyAllDevices();
      if (devices.count == 0) die("no Metal device");
      dev = devices[0];
      if (![dev supportsFamily:MTLGPUFamilyMetal3] || ![dev supportsFamily:MTLGPUFamilyApple7])
        die(std::string("this GPU (") + dev.name.UTF8String + ") is not an Apple-silicon GPU with Metal 3; LocalFold needs an M1 or later");
      queue = [dev newCommandQueueWithMaxCommandBufferCount:64];
      runtimeLib = compile(lf::RUNTIME_SOURCE, "the runtime's kernels");
    }
  }

  id<MTLLibrary> compile(const std::string& source, const std::string& what) {
    MTLCompileOptions* o = [MTLCompileOptions new];
    o.languageVersion = MTLLanguageVersion3_0;
    o.fastMathEnabled = NO;
    NSError* e = nil;
    id<MTLLibrary> lib = [dev newLibraryWithSource:[NSString stringWithUTF8String:source.c_str()] options:o error:&e];
    if (!lib) die("compiling " + what + ":\n" + (e ? e.localizedDescription.UTF8String : "?"));
    return lib;
  }

  // ---- memory
  const Alloc* find(uint64_t addr) {
    auto it = allocs.upper_bound(addr);
    if (it == allocs.begin()) return nullptr;
    --it;
    if (addr >= it->second.addr && addr < it->second.addr + std::max<size_t>(it->second.size, 1)) return &it->second;
    return nullptr;
  }
  void* host(const void* device) {
    const Alloc* a = find((uint64_t)device);
    if (!a) return nullptr;
    return (char*)a->buf.contents + ((uint64_t)device - a->addr);
  }
  void* host(const void* device, size_t bytes, const char* what) {
    const Alloc* a = find((uint64_t)device);
    if (!a) die(std::string(what) + ": not a device pointer");
    if ((uint64_t)device + bytes > a->addr + a->size) die(std::string(what) + ": past the end of its allocation");
    return (char*)a->buf.contents + ((uint64_t)device - a->addr);
  }
  void* malloc_(size_t bytes) {
    std::lock_guard<std::recursive_mutex> l(mu);
    size_t n = std::max<size_t>((bytes + 255) & ~(size_t)255, 256);
    id<MTLBuffer> b = [dev newBufferWithLength:n options:MTLResourceStorageModeShared |
                       (untracked ? MTLResourceHazardTrackingModeUntracked : 0)];
    ++stats.allocs;
    if (!b) return nullptr;
    uint64_t addr = b.gpuAddress;
    allocs[addr] = {b, addr, bytes};
    allocated += n; peak = std::max(peak, allocated);
    if (enc) [enc useResource:b usage:MTLResourceUsageRead | MTLResourceUsageWrite];
    return (void*)addr;
  }
  void free_(void* p) {
    if (!p) return;
    std::lock_guard<std::recursive_mutex> l(mu);
    auto it = allocs.find((uint64_t)p);
    if (it == allocs.end()) return;
    allocated -= std::max<size_t>((it->second.size + 255) & ~(size_t)255, 256);
    cbKeep.push_back(it->second.buf);           // (alive until the work that may use it is done)
    allocs.erase(it);
  }

  // ---- the queue
  void ensureEncoder() {
    if (enc) return;
    if (!cb) cb = [queue commandBufferWithUnretainedReferences];
    enc = [cb computeCommandEncoderWithDispatchType:MTLDispatchTypeSerial];
    ++stats.encoders;
    encodedInEncoder = 0;
    std::vector<id<MTLResource>> all;
    all.reserve(allocs.size());
    for (auto& [_, a] : allocs) all.push_back(a.buf);
    if (!all.empty()) [enc useResources:all.data() count:all.size() usage:MTLResourceUsageRead | MTLResourceUsageWrite];
  }
  void commit() {
    if (enc) { [enc endEncoding]; enc = nil; }
    if (!cb) return;
    if (!cbKeep.empty()) {
      __block std::vector<id<MTLBuffer>> keep = std::move(cbKeep);
      cbKeep.clear();
      [cb addCompletedHandler:^(id<MTLCommandBuffer>) { keep.clear(); }];
    }
    // every command buffer reports a failure, not only the last before a sync: one committed mid-stream (every 256
    // dispatches) that fails - out of memory under another process's load, the GPU's watchdog - skips its work, and
    // unchecked the fold would carry on from the skipped work's buffers as if it had run
    long seq;
    { std::lock_guard<std::mutex> g(inflightMu); seq = ++committedSeq; pending.insert(seq); }
    [cb addCompletedHandler:^(id<MTLCommandBuffer> done) {
      if (done.error) {
        std::lock_guard<std::mutex> g(gpuErrorMu);
        if (gpuError.empty()) gpuError = done.error.localizedDescription.UTF8String;
      }
      { std::lock_guard<std::mutex> g(inflightMu); pending.erase(seq); }
      inflightDone.notify_all();
    }];
    [cb commit];
    ++stats.commits;
    lastCommitted = cb;
    cb = nil;
    encoded = 0;
  }
  void sync() {
    std::lock_guard<std::recursive_mutex> l(mu);
    commit();
    ++stats.syncs;
    if (lastCommitted) {
      auto t0 = std::chrono::steady_clock::now();
      [lastCommitted waitUntilCompleted];
      stats.syncMs += std::chrono::duration<double, std::milli>(std::chrono::steady_clock::now() - t0).count();
      if (lastCommitted.error) die(std::string("the GPU failed: ") + lastCommitted.error.localizedDescription.UTF8String);
      lastCommitted = nil;
    }
    // ...and EVERY command buffer done, not just the last: Metal may finish one it sees no dependency on before an
    // earlier one, and a host read after a sync must see all of them
    waitThrough(LONG_MAX);
    std::lock_guard<std::mutex> g(gpuErrorMu);
    if (!gpuError.empty()) die("the GPU failed: " + gpuError);
  }
  // idle: nothing encoded and nothing in flight - every committed command buffer completed (the last alone completing
  // says nothing of an earlier one Metal ran beside it), so a host write straight into a buffer cannot race the GPU
  bool idle() { std::lock_guard<std::mutex> g(inflightMu); return !cb && pending.empty(); }
  // every command buffer committed at or before `seq` complete (an event's wait: the work before its record)
  void waitThrough(long seq) {
    std::unique_lock<std::mutex> g(inflightMu);
    inflightDone.wait(g, [&] { return pending.empty() || *pending.begin() > seq; });
  }

  // a runtime kernel that is a template (the GEMM): its explicit instantiation compiled with the runtime's source on
  // first use, as the port's kernels are
  id<MTLComputePipelineState> runtimeInstance(const std::string& host, const std::string& decl) {
    auto it = runtimePipelines.find(host);
    if (it != runtimePipelines.end()) return it->second;
    auto t0 = std::chrono::steady_clock::now();
    id<MTLLibrary> lib = compile(std::string(lf::RUNTIME_SOURCE) + "\n" + decl + "\n", host);
    stats.compileMs += std::chrono::duration<double, std::milli>(std::chrono::steady_clock::now() - t0).count();
    id<MTLComputePipelineState> p = pipelineOf(lib, host);
    runtimePipelines[host] = p;
    return p;
  }
  id<MTLComputePipelineState> runtimePipeline(const std::string& name) {
    auto it = runtimePipelines.find(name);
    if (it != runtimePipelines.end()) return it->second;
    id<MTLFunction> f = [runtimeLib newFunctionWithName:[NSString stringWithUTF8String:name.c_str()]];
    if (!f) die("no runtime kernel " + name);
    NSError* e = nil;
    id<MTLComputePipelineState> p = [dev newComputePipelineStateWithFunction:f error:&e];
    if (!p) die("runtime kernel " + name + ": " + e.localizedDescription.UTF8String);
    runtimePipelines[name] = p;
    return p;
  }
  void dispatch(id<MTLComputePipelineState> pso, const void* args, size_t argBytes, MTLSize grid, MTLSize block,
                size_t smem, const std::string& label = "") {
    if (grid.width == 0 || grid.height == 0 || grid.depth == 0) return;
    if (capturingHere()) {
      Op op{}; op.kind = 0; op.pso = pso; op.args.assign((const unsigned char*)args, (const unsigned char*)args + argBytes);
      op.grid = grid; op.block = block; op.smem = smem; op.label = label;
      capture->push_back(std::move(op));
      return;
    }
    // a pipeline's thread limit falls as its kernel takes registers, and Metal does not run a dispatch past it - no error,
    // the output left as it was - so the dispatch is refused here, naming the kernel
    if (block.width * block.height * block.depth > pso.maxTotalThreadsPerThreadgroup)
      die("a dispatch of " + std::to_string(block.width * block.height * block.depth) + " threads a threadgroup to a kernel that takes at most " +
          std::to_string(pso.maxTotalThreadsPerThreadgroup) + (label.empty() ? std::string("") : " (" + label + ")"));
    ensureEncoder();
    ++stats.dispatches;
    [enc setComputePipelineState:pso];
    if (argBytes <= 4096) [enc setBytes:args length:std::max<size_t>(argBytes, 4) atIndex:0];
    else {
      id<MTLBuffer> b = [dev newBufferWithBytes:args length:argBytes options:MTLResourceStorageModeShared];
      if (!b) die("out of memory for a kernel's arguments (" + std::to_string(argBytes) + " bytes)");
      cbKeep.push_back(b);
      [enc setBuffer:b offset:0 atIndex:0];
    }
    [enc setThreadgroupMemoryLength:std::max<size_t>((smem + 15) & ~(size_t)15, 16) atIndex:0];
    // (untracked buffers: the order between this dispatch and the last is the barrier's)
    if (encodedInEncoder++ && untracked) [enc memoryBarrierWithScope:MTLBarrierScopeBuffers];
    [enc dispatchThreadgroups:grid threadsPerThreadgroup:block];
    if (profiling && !label.empty()) {      // (a command buffer a dispatch: its GPU time is the kernel's)
      id<MTLCommandBuffer> mine = cb;
      commit();
      profiled.push_back({label, mine});
    } else if (++encoded >= 256) {
      ++stats.commitsThreshold;
      commit();                             // (let the GPU start while the host encodes the rest)
    }
  }
  void copy(uint64_t dst, uint64_t src, size_t bytes) {
    ++stats.copies;
    struct { uint64_t dst, src, bytes; } a = {dst, src, bytes};
    size_t threads = ((dst | src) & 15) == 0 ? std::max<size_t>(bytes / 16, 16) : bytes;
    size_t groups = (threads + 255) / 256;
    MTLSize grid = groups > 65535 ? MTLSizeMake(65535, (groups + 65534) / 65535, 1) : MTLSizeMake(groups, 1, 1);
    if (capturingHere()) {
      Op op{}; op.kind = 1; op.dst = dst; op.src = src; op.bytes = bytes; capture->push_back(op); return;
    }
    dispatch(runtimePipeline("lf_copy"), &a, sizeof a, grid, MTLSizeMake(256, 1, 1), 0);
  }
  void fill(uint64_t dst, int value, size_t bytes) {
    ++stats.fills;
    struct { uint64_t dst, bytes; uint32_t value; uint32_t pad; } a = {dst, bytes, (uint32_t)value, 0};
    size_t threads = (dst & 15) == 0 ? std::max<size_t>(bytes / 16, 16) : bytes;
    size_t groups = (threads + 255) / 256;
    MTLSize grid = groups > 65535 ? MTLSizeMake(65535, (groups + 65534) / 65535, 1) : MTLSizeMake(groups, 1, 1);
    if (capturingHere()) {
      Op op{}; op.kind = 2; op.dst = dst; op.bytes = bytes; op.value = value; capture->push_back(op); return;
    }
    dispatch(runtimePipeline("lf_fill"), &a, sizeof a, grid, MTLSizeMake(256, 1, 1), 0);
  }

  // ---- the port's kernels
  void loadSpecs() {
    if (specsLoaded) return;
    specsLoaded = true;
    const char* home = getenv("HOME");
    std::string dir = std::string(home ? home : "/tmp") + "/.cache/localfold/metal";
    mkdir((std::string(home ? home : "/tmp") + "/.cache").c_str(), 0755);
    mkdir((std::string(home ? home : "/tmp") + "/.cache/localfold").c_str(), 0755);
    mkdir(dir.c_str(), 0755);
    size_t h = std::hash<std::string>()(lf::PORT_SOURCE);
    char name[64]; snprintf(name, sizeof name, "/%s-%016zx.specs", lf::PORT_NAME, h);
    specsPath = dir + name;
    // a first run: the list a wheel ships beside the binary (bin/metal-specs/<port>-<hash>.specs, the specialisations
    // its build's folds used), so even a first fold compiles its kernels up front and in parallel
    struct stat st;
    if (stat(specsPath.c_str(), &st) != 0) {
      char exe[4096]; uint32_t size = sizeof exe;
      if (_NSGetExecutablePath(exe, &size) == 0) {
        std::string bundled = std::string(exe);
        bundled = bundled.substr(0, bundled.rfind('/')) + "/metal-specs" + name;
        std::ifstream src(bundled);
        if (src) { std::ofstream dst(specsPath); dst << src.rdbuf(); }
      }
    }
    std::ifstream in(specsPath);
    std::string line, inst;
    std::vector<std::string> names;
    while (std::getline(in, line)) {
      size_t tab = line.find('\t');
      if (tab == std::string::npos) continue;
      knownSpecs.insert(line.substr(0, tab));
      names.push_back(line.substr(0, tab));
      inst += line.substr(tab + 1) + "\n";
    }
    if (names.empty()) return;
    // every specialisation a previous run used, in one library (and in parallel chunks: the compiler is single-threaded)
    size_t chunks = std::min<size_t>(8, (names.size() + 15) / 16);
    std::vector<std::string> parts(chunks);
    std::vector<std::vector<std::string>> partNames(chunks);
    {
      std::istringstream lines(inst);
      size_t k = 0;
      while (std::getline(lines, line)) { parts[k % chunks] += line + "\n"; partNames[k % chunks].push_back(names[k]); ++k; }
    }
    // ...and each chunk's pipelines made on its own thread too: a pipeline is where the GPU's own compiler runs, and on
    // a cold system cache that was most of an AF3 first fold's ~10 s of compiling, one pipeline at a time
    std::vector<std::vector<id<MTLComputePipelineState>>> made(chunks);
    std::vector<std::thread> threads;
    for (size_t c = 0; c < chunks; ++c)
      threads.emplace_back([&, c] { @autoreleasepool {
        id<MTLLibrary> lib = compile(std::string(lf::PORT_SOURCE) + parts[c], "the cached kernels");
        for (auto& n : partNames[c]) made[c].push_back(pipelineOf(lib, n));
      } });
    for (auto& t : threads) t.join();
    for (size_t c = 0; c < chunks; ++c)
      for (size_t i = 0; i < partNames[c].size(); ++i) pipelines[partNames[c][i]] = made[c][i];
  }
  id<MTLComputePipelineState> pipelineOf(id<MTLLibrary> lib, const std::string& host) {
    id<MTLFunction> f = [lib newFunctionWithName:[NSString stringWithUTF8String:host.c_str()]];
    if (!f) die("no compiled kernel " + host);
    NSError* e = nil;
    id<MTLComputePipelineState> p = [dev newComputePipelineStateWithFunction:f error:&e];
    if (!p) die(host + ": " + (e ? e.localizedDescription.UTF8String : "?"));
    return p;
  }
  id<MTLComputePipelineState> kernel(int index, const std::string& targs) {
    const lf::KernelInfo& k = lf::PORT_KERNELS[index];
    std::string host = k.structName;
    host += "__" + targs;
    for (char& c : host) if (!isalnum((unsigned char)c) && c != '_') c = '_';
    auto it = pipelines.find(host);
    if (it != pipelines.end()) return it->second;
    loadSpecs();
    it = pipelines.find(host);
    if (it != pipelines.end()) return it->second;
    if (k.status == 2) die(std::string("kernel ") + k.name + " has no Metal translation yet (it is " +
                           "inline PTX or uses a construct cu2metal.py cannot translate) and nothing overrides it");
    std::string inst = std::string("template [[host_name(\"") + host + "\")]] kernel void " + k.name + "<" + targs +
                       ">(constant " + k.structName + "<" + targs + ">&, threadgroup char*, uint3, uint3, uint3, uint3, uint, uint, uint);";
    auto t0 = std::chrono::steady_clock::now();
    id<MTLLibrary> lib = compile(std::string(lf::PORT_SOURCE) + "\n" + inst + "\n", std::string("kernel ") + k.name + "<" + targs + ">");
    stats.compileMs += std::chrono::duration<double, std::milli>(std::chrono::steady_clock::now() - t0).count();
    id<MTLComputePipelineState> p = pipelineOf(lib, host);
    if (getenv("LOCALFOLD_METAL_VERBOSE"))
      fprintf(stderr, "metal: compiled %s<%s> in %.0f ms\n", k.name, targs.c_str(),
              std::chrono::duration<double, std::milli>(std::chrono::steady_clock::now() - t0).count());
    pipelines[host] = p;
    if (!knownSpecs.count(host)) {
      knownSpecs.insert(host);
      std::ofstream out(specsPath, std::ios::app);
      out << host << "\t" << inst << "\n";
    }
    return p;
  }
};

// LOCALFOLD_METAL_SPECS_NAME=1: print this binary's specialisation list's file name and exit (python/build_wheel_macos.sh)
__attribute__((constructor)) static void printSpecsName() {
  if (!getenv("LOCALFOLD_METAL_SPECS_NAME")) return;
  printf("%s-%016zx.specs\n", lf::PORT_NAME, std::hash<std::string>()(lf::PORT_SOURCE));
  exit(0);
}
Runtime& R() {
  static Runtime* r = [] {
    Runtime* rt = new Runtime();
    if (rt->statsOn) atexit([] {
      auto& s = R().stats;
      fprintf(stderr, "metal stats: %ld launches %.1f ms encoding, %ld syncs %.1f ms waiting, %ld commits, %ld encoders, "
              "%ld staged copies, %ld allocations, %zu live, compiles %.0f ms; commits by threshold %ld, by event %ld; %ld dispatches, %ld graph launches of %ld ops, %ld captures of %ld ops; copies %ld fills %ld gemms %ld memcpy %ld memset %ld\n", s.launches, s.launchMs, s.syncs, s.syncMs,
              s.commits, s.encoders, s.staged, s.allocs, R().allocs.size(), s.compileMs, s.commitsThreshold, s.commitsEvent, s.dispatches, s.graphLaunches, s.graphOps, s.captures, s.capturedOps, s.copies, s.fills, s.gemms, s.memcpyCalls, s.memsetCalls);
    });
    return rt;
  }();
  return *r;
}
