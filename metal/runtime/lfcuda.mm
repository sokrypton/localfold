cublasStatus_t cublasLtMatmul(cublasLtHandle_t, cublasLtMatmulDesc_t d, const void* alpha, const void* A, cublasLtMatrixLayout_t la,
                              const void* B, cublasLtMatrixLayout_t lb, const void* beta, const void* C, cublasLtMatrixLayout_t lc,
                              void* D, cublasLtMatrixLayout_t ld, const cublasLtMatmulAlgo_t*, void*, size_t, cudaStream_t) {
  if (la->order || lb->order || lc->order || ld->order) die("cuBLASLt with a row-major layout");
  int m = (int)ld->rows, n = (int)ld->cols, k = d->ta ? (int)la->rows : (int)la->cols;
  int epi = d->epilogue == CUBLASLT_EPILOGUE_RELU ? 2 : d->epilogue == CUBLASLT_EPILOGUE_BIAS ? 4
          : d->epilogue == CUBLASLT_EPILOGUE_RELU_BIAS ? 6 : d->epilogue == CUBLASLT_EPILOGUE_GELU ? 32
          : d->epilogue == CUBLASLT_EPILOGUE_GELU_BIAS ? 36 : 0;
  int biasType = d->biasType ? d->biasType : ld->type;
  GemmArgs a{(uint64_t)A, (uint64_t)B, (uint64_t)C, (uint64_t)D, (uint64_t)d->bias, la->stride, lb->stride, lc->stride, ld->stride,
             m, n, k, (int)la->ld, (int)lb->ld, (int)lc->ld, (int)ld->ld, d->ta != 0, d->tb != 0, 0, epi, biasType,
             scalar(alpha, (cublasComputeType_t)d->compute), scalar(beta, (cublasComputeType_t)d->compute)};
  if ((cudaDataType)lc->type != (cudaDataType)ld->type && *(const float*)beta != 0.f) die("cuBLASLt with C and D of different types");
  gemm((cudaDataType)la->type, (cudaDataType)lb->type, (cudaDataType)ld->type, a, std::max(ld->batch, 1));
  return CUBLAS_STATUS_SUCCESS;
}
