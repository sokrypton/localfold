#!/usr/bin/env python3
"""Generate shared/rfd4p/pipeline/query-tables.js from atomworks' and biotite's own constants.

    ~/venv_rfd4p/bin/python tools/gen-rfd4p-query-tables.py [--check]

The selection language upstream evaluates (`atomworks.io.utils.query.QueryExpression`) derives
forty annotations on demand - `is_protein_backbone`, `is_tip_atom`, `is_metal`, `is_carbohydrate`
and the rest - from these tables. Generated, never typed: a backbone atom list copied by hand is a
selection that disagrees with upstream on the atom nobody checked. `--check` fails when stale.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
OUT = REPO / "shared" / "rfd4p" / "pipeline" / "query-tables.js"

HEADER = """// GENERATED by tools/gen-rfd4p-query-tables.py from atomworks' and biotite's constants - do
// not edit. The tables upstream's selection language derives its annotations from.
//
// atomworks: Copyright (c) 2025, Institute for Protein Design, University of Washington.
// biotite (`carbohydrate_names`): Copyright 2017, The Biotite contributors.
// Both redistributed under their BSD 3-Clause Licenses: redistributions must retain these
// copyright notices, this list of conditions and the following disclaimer. THIS DATA IS PROVIDED
// BY THE COPYRIGHT HOLDERS AND CONTRIBUTORS "AS IS" AND ANY EXPRESS OR IMPLIED WARRANTIES,
// INCLUDING, BUT NOT LIMITED TO, THE IMPLIED WARRANTIES OF MERCHANTABILITY AND FITNESS FOR A
// PARTICULAR PURPOSE ARE DISCLAIMED. Neither the name of the copyright holders nor the names of
// their contributors may be used to endorse or promote products derived from this software
// without specific prior written permission.
"""


def tables() -> dict:
    import atomworks.constants as K
    from atomworks.enums import ChainType
    from biotite.structure.info.groups import carbohydrate_names

    return {
        "PROTEIN_BACKBONE_ATOM_NAMES": list(K.PROTEIN_BACKBONE_ATOM_NAMES),
        "RNA_BACKBONE_ATOM_NAMES": list(K.RNA_BACKBONE_ATOM_NAMES),
        "DNA_BACKBONE_ATOM_NAMES": list(K.DNA_BACKBONE_ATOM_NAMES),
        "NUCLEIC_ACID_BACKBONE_ATOM_NAMES": list(K.NUCLEIC_ACID_BACKBONE_ATOM_NAMES),
        "STANDARD_AA": list(K.STANDARD_AA),
        "STANDARD_RNA": list(K.STANDARD_RNA),
        "STANDARD_DNA": list(K.STANDARD_DNA),
        "UNKNOWN_AA": K.UNKNOWN_AA,
        "UNKNOWN_RNA": K.UNKNOWN_RNA,
        "UNKNOWN_DNA": K.UNKNOWN_DNA,
        "MASKED": K.MASKED,
        "PYRIMIDINE_RESIDUES": list(K.STANDARD_PYRIMIDINE_RESIDUES),
        "PURINE_RESIDUES": list(K.STANDARD_PURINE_RESIDUES),
        "TIP_ATOM_NAMES": {k: list(v) for k, v in K.STANDARD_AA_TIP_ATOM_NAMES.items()},
        "METAL_ELEMENTS": sorted(K.METAL_ELEMENTS),
        "CHAIN_TYPE": {c.name: int(c.value) for c in ChainType},
        "PROTEIN_CHAIN_TYPES": sorted(int(c) for c in ChainType.get_proteins()),
        "NUCLEIC_CHAIN_TYPES": sorted(int(c) for c in ChainType.get_nucleic_acids()),
        "POLYMER_CHAIN_TYPES": sorted(int(c) for c in ChainType.get_polymers()),
        "NON_POLYMER_CHAIN_TYPES": sorted(int(c) for c in ChainType.get_non_polymers()),
        "CARBOHYDRATE_NAMES": sorted(carbohydrate_names()),
    }


def render(t: dict) -> str:
    body = "".join(f"export const {k} = Object.freeze({json.dumps(v, separators=(',', ':'))});\n"
                   for k, v in t.items())
    return HEADER + "\n" + body


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = render(tables())
    if args.check:
        if OUT.exists() and OUT.read_text() == text:
            print(f"{OUT.relative_to(REPO)} is current")
            return 0
        print(f"{OUT.relative_to(REPO)} is STALE - run tools/gen-rfd4p-query-tables.py", file=sys.stderr)
        return 1
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(REPO)}: {len(t := tables())} tables, "
          f"{len(t['CARBOHYDRATE_NAMES'])} carbohydrate names")
    return 0


if __name__ == "__main__":
    sys.exit(main())
