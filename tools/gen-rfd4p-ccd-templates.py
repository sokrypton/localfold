#!/usr/bin/env python3
"""Generate shared/rfd4p/pipeline/ccd-templates.js from the Chemical Component Dictionary atomworks reads.

    ~/venv_rfd4p/bin/python tools/gen-rfd4p-ccd-templates.py [--check]

A raw structure handed to a condition spec is PREPARED upstream (`RCSB_WITH_METALS`): each
residue completed to its CCD template, its atoms put in the template's order, its formal charges
taken from the template. Those templates are biotite's bundled CCD, which is 49,195 components
and too large to ship to a page; what is generated here is the part every prepared structure
needs - the standard polymer residues, their unknowns, MSE (which preparation turns into MET)
and every single-atom component (the ions) - and a component outside it is read from the file's
own `_chem_comp_atom` or fetched (shared/rfd4p/pipeline/ccd.js). `--check` fails when stale.
"""
from __future__ import annotations

import argparse
import json
import sys
from collections import Counter
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
OUT = REPO / "shared" / "rfd4p" / "pipeline" / "ccd-templates.js"

HEADER = """// GENERATED by tools/gen-rfd4p-ccd-templates.py from the Chemical Component Dictionary bundled
// with biotite (the one atomworks reads) - do not edit.
//
// Each component: its `_chem_comp.type` and its HEAVY atoms in the dictionary's order, as
// [atom_id, alt_atom_id, type_symbol, charge, leaving (0/1), aromatic (0/1)].
//
// The CCD is the wwPDB's, distributed without restriction; biotite (which bundles it):
// Copyright 2017, The Biotite contributors, BSD 3-Clause License - redistributions must retain
// this notice. THIS DATA IS PROVIDED "AS IS" AND ANY EXPRESS OR IMPLIED WARRANTIES ARE DISCLAIMED.
"""


def tables() -> dict:
    import numpy as np
    from atomworks.constants import (STANDARD_AA, STANDARD_DNA, STANDARD_RNA, UNKNOWN_AA, UNKNOWN_DNA,
                                     UNKNOWN_RNA, WATER_LIKE_CCDS)
    from biotite.structure.info.ccd import get_ccd

    ccd = get_ccd()
    atom = ccd["chem_comp_atom"]
    comp = ccd["chem_comp"]
    ids = atom["comp_id"].as_array(str)
    count = Counter(ids)
    wanted = set(STANDARD_AA) | set(STANDARD_RNA) | set(STANDARD_DNA) | {UNKNOWN_AA, UNKNOWN_RNA, UNKNOWN_DNA, "MSE"}
    wanted |= {k for k, v in count.items() if v == 1}
    cols = {k: atom[k].as_array(str) for k in ("atom_id", "alt_atom_id", "type_symbol", "charge",
                                                 "pdbx_leaving_atom_flag", "pdbx_aromatic_flag")}
    types = dict(zip(comp["id"].as_array(str), comp["type"].as_array(str), strict=True))
    out = {}
    for i, cid in enumerate(ids):
        # Heavy atoms only: a prepared structure's hydrogens never reach the batch (the pipeline
        # drops them), and preparation here drops them once the alternate locations are chosen.
        if cid not in wanted or cols["type_symbol"][i] in ("H", "D"):
            continue
        entry = out.setdefault(str(cid), {"type": types.get(cid, "").upper(), "atoms": []})
        charge = cols["charge"][i]
        entry["atoms"].append([str(cols["atom_id"][i]), str(cols["alt_atom_id"][i]), str(cols["type_symbol"][i]),
                               int(charge) if charge not in ("?", ".") else 0,
                               int(cols["pdbx_leaving_atom_flag"][i] == "Y"),
                               int(cols["pdbx_aromatic_flag"][i] == "Y")])
    return {"CCD_TEMPLATES": dict(sorted(out.items())), "WATER_LIKE_CCDS": list(WATER_LIKE_CCDS)}


def render(t: dict) -> str:
    lines = [HEADER, f"export const WATER_LIKE_CCDS = Object.freeze({json.dumps(t['WATER_LIKE_CCDS'])});",
             "", "export const CCD_TEMPLATES = Object.freeze({"]
    for code, entry in t["CCD_TEMPLATES"].items():
        lines.append(f"  {json.dumps(code)}: {json.dumps(entry, separators=(',', ':'))},")
    lines.append("});")
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    t = tables()
    text = render(t)
    if args.check:
        if OUT.exists() and OUT.read_text() == text:
            print(f"{OUT.relative_to(REPO)} is current")
            return 0
        print(f"{OUT.relative_to(REPO)} is STALE - run tools/gen-rfd4p-ccd-templates.py", file=sys.stderr)
        return 1
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(REPO)}: {len(t['CCD_TEMPLATES'])} components")
    return 0


if __name__ == "__main__":
    sys.exit(main())
