#!/usr/bin/env python3
"""Write web/localfold-dark.css: py2Dmol's vendored stylesheet, in the page's dark tokens.

    python3 tools/dark-theme.py

py2Dmol's CSS is vendored and is not edited here, and most of its colours are literals. So
this reads it, finds every declaration with a colour that has a role, and writes the same
selector scoped to `:root[data-theme="dark"]` with that role's token. Run it after
re-vendoring; test/dark-theme.test.js fails when the file is stale. Colours with no role
(status greens and reds, the primary button) keep their value and need no rule.
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "web" / "vendor" / "py2Dmol.app.css"
OUT = ROOT / "web" / "localfold-dark.css"

BACKGROUND = {
    "#fff": "--lf-surface", "#ffffff": "--lf-surface", "white": "--lf-surface",
    "#f9fafb": "--lf-surface-2", "#f8fafc": "--lf-surface-2", "#f3f4f6": "--lf-surface-3",
    "#f5f5f4": "--lf-surface-3", "#f1f5f9": "--lf-surface-3", "#e5e7eb": "--lf-surface-4",
    "#eff6ff": "--lf-info-bg", "#dbeafe": "--lf-info-bg-2", "#fee2e2": "--lf-error-bg",
    "#fffbeb": "--lf-warn-bg", "#f0fdf4": "--lf-ok-bg",
}
TEXT = {
    "#000": "--lf-text", "#111827": "--lf-text", "#0f172a": "--lf-text", "#1f2937": "--lf-text",
    "#374151": "--lf-text-2", "#4b5563": "--lf-text-2", "#6b7280": "--lf-muted", "#64748b": "--lf-muted",
    "#9ca3af": "--lf-faint", "#991b1b": "--lf-error-text", "#b91c1c": "--lf-error-text",
    "#92400e": "--lf-warn-text", "#1e40af": "--lf-info-text", "#1d4ed8": "--lf-info-text",
}
BORDER = {
    "#d1d5db": "--lf-border", "#e5e7eb": "--lf-border-2", "#e2e8f0": "--lf-border-2", "#f3f4f6": "--lf-border-2",
    "#bfdbfe": "--lf-info-border", "#93c5fd": "--lf-info-border", "#fca5a5": "--lf-error-border",
    "#fde68a": "--lf-warn-border",
}
ROLE = {"background": BACKGROUND, "background-color": BACKGROUND, "color": TEXT,
        "border": BORDER, "border-color": BORDER, "border-top": BORDER, "border-bottom": BORDER,
        "border-left": BORDER, "border-right": BORDER, "outline": BORDER}
COLOUR = re.compile(r"#[0-9a-fA-F]{3,8}\b|\bwhite\b", re.I)


def rules(css):
    """(selector, body) for each rule, flattened out of @media blocks that have conditions kept."""
    css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
    for match in re.finditer(r"([^{}@][^{}]*)\{([^{}]*)\}", css):
        yield " ".join(match.group(1).split()), match.group(2)


def scoped(selector):
    parts = [part.strip() for part in selector.split(",")]
    kept = []
    for part in parts:
        if part.startswith(("from", "to", "0%", "100%")) or re.fullmatch(r"\d+%", part):
            return None
        if part in ("html", ":root"):
            kept.append(':root[data-theme="dark"]')
        else:
            kept.append(f':root[data-theme="dark"] {part}')
    return ",\n".join(kept)


def main():
    lines = ["/* Generated by tools/dark-theme.py from web/vendor/py2Dmol.app.css. Do not edit. */", ""]
    for selector, body in rules(SOURCE.read_text(encoding="utf-8")):
        out = []
        for declaration in body.split(";"):
            if ":" not in declaration:
                continue
            name, value = declaration.split(":", 1)
            name = name.strip().lower()
            table = ROLE.get(name)
            if table is None or "gradient" in value:
                continue
            changed = COLOUR.sub(lambda found: f"var({table[found.group(0).lower()]})"
                                 if found.group(0).lower() in table else found.group(0), value.strip())
            if changed != value.strip():
                out.append(f"  {name}: {changed};")
        target = scoped(selector)
        if out and target is not None:
            lines += [f"{target} {{", *out, "}", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    return len(lines)


if __name__ == "__main__":
    print(f"{main()} lines in {OUT.name}")
