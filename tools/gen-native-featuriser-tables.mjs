// Generate cuda/featurise/tables.inc - the data the native featuriser reads, from the JavaScript it mirrors.
//
//   node --js-float16array tools/gen-native-featuriser-tables.mjs           # write it
//   node --js-float16array tools/gen-native-featuriser-tables.mjs --check   # exit 1 if it is stale
//
// 🔴 GENERATED, NOT TRANSCRIBED. The baked reference conformers (shared/af3/featurise/reference-conformers*.js)
// and each family's featuriser conventions (shared/af3/dialect.js) are data the page's featuriser and the native
// one must agree on to the last digit; a hand copy is a second source of truth that drifts. Coordinates are
// written as JavaScript's own shortest round-trip form, so C++ parses each to the identical double.
// `npm test` (test/native-featuriser-tables.test.js) fails when the file is stale.
import { readFileSync, writeFileSync } from "node:fs";

const repo = new URL("..", import.meta.url).pathname;
const { REFERENCE_CONFORMERS, RESIDUE_TYPES } = await import(`${repo}shared/af3/featurise/reference-conformers.js`);
const { DNA_CONFORMERS, RNA_CONFORMERS } = await import(`${repo}shared/af3/featurise/reference-conformers-nucleic.js`);
const { DIALECTS, DIALECT_ALIASES, featuriserDialect } = await import(`${repo}shared/af3/dialect.js`);
const { ELEMENT_SYMBOLS } = await import(`${repo}shared/af3/featurise/ccd-component.js`);
const { AF3_MSA_CODES } = await import(`${repo}shared/af3/featurise/msa-features.js`);

const num = (v) => String(v);
const str = (s) => JSON.stringify(s);
const atoms = (list) => `{${list.map(([slot, name, element, charge, x, y, z]) =>
  `{${slot}, ${str(name)}, ${element}, ${num(charge)}, ${num(x)}, ${num(y)}, ${num(z)}}`).join(", ")}}`;

const lines = [
  "// GENERATED by tools/gen-native-featuriser-tables.mjs from the JavaScript featuriser's own data - do not edit.",
  "// Included by cuda/featurise/tables.h.",
  "",
  "// shared/af3/featurise/reference-conformers.js: the 21 protein components, [internal, C-terminal]",
  "inline const std::vector<ConformerEntry>& proteinConformers() {",
  "  static const std::vector<ConformerEntry> table = {",
];
for (const code of RESIDUE_TYPES) {
  const e = REFERENCE_CONFORMERS[code];
  lines.push(`    {'${code}', ${e.aatype}, ${atoms(e.internal)}, ${atoms(e.cTerminal)}},`);
}
lines.push("  };", "  return table;", "}", "");
for (const [kind, table] of [["dna", DNA_CONFORMERS], ["rna", RNA_CONFORMERS]]) {
  lines.push(`// shared/af3/featurise/reference-conformers-nucleic.js: ${kind.toUpperCase()}, [internal, 5'-terminal]`);
  lines.push(`inline const std::vector<ConformerEntry>& ${kind}Conformers() {`);
  lines.push("  static const std::vector<ConformerEntry> table = {");
  for (const [code, e] of Object.entries(table)) {
    lines.push(`    {'${code}', ${e.aatype}, ${atoms(e.internal)}, ${atoms(e.fivePrime)}},`);
  }
  lines.push("  };", "  return table;", "}", "");
}
lines.push("// shared/af3/featurise/ccd-component.js ELEMENT_SYMBOLS (atomic number - 1)");
lines.push(`inline const std::vector<std::string>& elementSymbols() { static const std::vector<std::string> s = {${ELEMENT_SYMBOLS.map(str).join(", ")}}; return s; }`);
lines.push("");
lines.push("// shared/af3/featurise/msa-features.js AF3_MSA_CODES (the protein alphabet; anything else X)");
lines.push(`inline int af3MsaCode(char c) { switch (c) { ${Object.entries(AF3_MSA_CODES).map(([k, v]) => `case '${k}': return ${v};`).join(" ")} default: return -1; } }`);
lines.push("");
lines.push("// shared/af3/dialect.js: each family's featuriser conventions (featuriserDialect) and the export's own");
lines.push("inline const std::vector<FamilyFlags>& familyFlags() {");
lines.push("  static const std::vector<FamilyFlags> table = {");
const bool = (v) => (v === true ? "true" : "false");
for (const [name, d] of Object.entries(DIALECTS)) {
  const f = featuriserDialect(d);
  const drop = f.dropTerminalAtoms === true ? 1 : f.dropTerminalAtoms === "protein" ? 2 : 0;
  const dedupe = f.dedupeSelfMsa === undefined ? -1 : f.dedupeSelfMsa ? 1 : 0;
  const fused = d.fusedTemplateLayout ?? null;
  lines.push(`    {${str(name)}, ${bool(f.symmetriseBonds)}, ${bool(f.centreRefConformers)}, ${bool(f.paddedAtomKeys)},`
    + ` ${bool(f.qblockAtomKeys)}, ${drop}, ${dedupe}, ${bool(f.atomizedElementNames)}, ${bool(f.atomizedUnknownRestype)},`
    + ` ${bool(f.atomizedUnknownMsa)}, ${bool(f.atomizedBackboneBonds)}, ${bool(f.modifiedAsOneToken)}, ${bool(f.chaiMsaFeatures)},`
    + ` ${fused ? fused.distogramBins : 0}, ${fused ? fused.restypes : 0}, ${bool(d.boltz2TemplateFeatures)},`
    + ` ${bool(d.rosettafold3TemplateFeatures)}, ${bool(d.templateFeatureMeanOnePass)}, ${d.emptyTemplateAatype ?? -1},`
    + ` ${bool(d.templateVisibilityByCoverage)}, ${bool(d.chaiTemplates)}, ${bool(d.templateStackOuterResidual)},`
    + ` ${bool(d.chaiTokenEmbedding)}, ${bool(d.structuralTokens)}, ${bool(d.chiralCentres)},`
    + ` ${d.emptyTemplateRestypeColumns === undefined ? 0 : d.emptyTemplateRestypeColumns === null ? 1 : 2},`
    + ` {${(d.emptyTemplateRestypeColumns ?? []).join(", ")}}},`);
}
lines.push("  };", "  return table;", "}", "");
lines.push("// shared/af3/dialect.js DIALECT_ALIASES");
lines.push(`inline const std::vector<std::pair<std::string, std::string>>& familyAliases() { static const std::vector<std::pair<std::string, std::string>> a = {${Object.entries(DIALECT_ALIASES).map(([k, v]) => `{${str(k)}, ${str(v)}}`).join(", ")}}; return a; }`);
const text = `${lines.join("\n")}\n`;

const target = `${repo}cuda/featurise/tables.inc`;
if (process.argv.includes("--check")) {
  let current = "";
  try { current = readFileSync(target, "utf8"); } catch { /* absent is stale */ }
  if (current !== text) {
    console.error("cuda/featurise/tables.inc is stale: run node --js-float16array tools/gen-native-featuriser-tables.mjs");
    process.exit(1);
  }
  console.log("cuda/featurise/tables.inc is current");
} else {
  writeFileSync(target, text);
  console.log(`wrote cuda/featurise/tables.inc (${text.length} bytes)`);
}
