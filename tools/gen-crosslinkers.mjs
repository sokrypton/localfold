// Generate shared/chem/crosslinkers.js - the crosslinkers a `crosslinks` job names - from af3-any-model's export:
//
//   python -m alphafold3.common.crosslinks --export crosslinkers.json      (in af3-any-model)
//   node tools/gen-crosslinkers.mjs crosslinkers.json [af3-any-model commit]
//
// 🔴 GENERATED, NOT TRANSCRIBED, for the reason tools/gen-native-featuriser-tables.mjs gives: the bridge components
// (atoms, names, ideal geometry), which atom each end bonds and the per-residue diazirine atom are data
// af3-any-model and both featurisers here must agree on exactly. That module (src/alphafold3/common/crosslinks.py)
// is the source; this one is copied from it, never edited.
import { readFileSync, writeFileSync } from "node:fs";

const [source, commit = "unknown"] = process.argv.slice(2);
if (source === undefined) {
  console.error("usage: node tools/gen-crosslinkers.mjs crosslinkers.json [af3-any-model commit]");
  process.exit(2);
}
const data = JSON.parse(readFileSync(source, "utf8"));
const repo = new URL("..", import.meta.url).pathname;
const text = `/**
 * The crosslinkers a \`crosslinks\` job names (af3x's input), as af3-any-model defines them.
 *
 * GENERATED by tools/gen-crosslinkers.mjs from af3-any-model ${commit} (src/alphafold3/common/crosslinks.py,
 * \`--export\`) - do not edit. Each crosslinker is its REACTED bridge, a component of its own (code XL-<name>);
 * \`attach\` names the bridge atoms its two ends bond, \`ends\` what reacts there: an NHS ester (\`nhsAtoms\`, or
 * residue 1's N) or a diazirine (\`diazirineAtoms\`, the residue's last side-chain atom).
 */
export const CROSSLINKERS = ${JSON.stringify(data.crosslinkers, null, 1)};
export const CROSSLINKER_ALIASES = ${JSON.stringify(data.aliases)};
export const NHS_ATOMS = ${JSON.stringify(data.nhsAtoms)};
export const DIAZIRINE_ATOMS = ${JSON.stringify(data.diazirineAtoms)};
/** Each bridge's mmCIF block, by its code: what parseCcdComponent reads in place of a fetched entry. */
export const CROSSLINKER_COMPONENTS = ${JSON.stringify(data.components, null, 1)};

/** A crosslinker by name, as af3x and the suppliers write them (sulfo-SDA, BS(PEG)5, ...) - or null. */
export function crosslinker(name) {
  const key = String(name).trim().toUpperCase();
  return CROSSLINKERS[CROSSLINKER_ALIASES[key] ?? key] ?? null;
}
`;
writeFileSync(`${repo}shared/chem/crosslinkers.js`, text);
console.log(`wrote shared/chem/crosslinkers.js (${Object.keys(data.crosslinkers).length} crosslinkers)`);
