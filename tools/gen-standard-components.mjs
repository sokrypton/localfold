// Generate shared/af3/featurise/standard-components.js - the CCD entries of the 20 standard amino acids and the 8
// standard nucleotides, cut down to what parseCcdComponent reads - from ccd/components.cif. Hydrogens are kept: rf3's
// declared-bond charge counts the bonds an atom still has, a hydrogen's among them.
//
//   node tools/gen-standard-components.mjs [ccd/components.cif]
//
// The featuriser atomises a STANDARD residue for rf3 when a declared bond ties it to a ligand (atomworks'
// covalent_modifications: af3-any-model's atomize_ligand_bonded), and then needs the residue's own atoms and bonds,
// which the reference conformer tables do not carry.
import { readFileSync, writeFileSync } from "node:fs";
import { loopOf } from "../shared/af3/featurise/ccd-component.js";

const repo = new URL("..", import.meta.url).pathname;
const source = process.argv[2] ?? `${repo}ccd/components.cif`;
const CODES = ["ALA", "ARG", "ASN", "ASP", "CYS", "GLN", "GLU", "GLY", "HIS", "ILE", "LEU", "LYS", "MET", "PHE",
  "PRO", "SER", "THR", "TRP", "TYR", "VAL", "DA", "DC", "DG", "DT", "A", "C", "G", "U"];
const text = readFileSync(source, "utf8");
const ATOM_COLUMNS = ["comp_id", "atom_id", "type_symbol", "charge", "pdbx_leaving_atom_flag",
  "model_Cartn_x", "model_Cartn_y", "model_Cartn_z",
  "pdbx_model_Cartn_x_ideal", "pdbx_model_Cartn_y_ideal", "pdbx_model_Cartn_z_ideal"];
const BOND_COLUMNS = ["comp_id", "atom_id_1", "atom_id_2", "value_order", "pdbx_aromatic_flag"];
const quote = (v) => (/[\s'"]/.test(v) ? `"${v}"` : v);
const out = {};
for (const code of CODES) {
  const start = text.indexOf(`\ndata_${code}\n`);
  if (start < 0) throw new Error(`${code} is not in ${source}`);
  const end = text.indexOf("\ndata_", start + 1);
  const block = text.slice(start + 1, end < 0 ? text.length : end);
  const value = (key) => block.match(new RegExp(`\\n${key.replace(".", "\\.")}\\s+("[^"]*"|'[^']*'|\\S+)`))?.[1];
  const atoms = loopOf(block, "_chem_comp_atom");
  const bonds = loopOf(block, "_chem_comp_bond");
  const at = (loop, row, name) => row[loop.columns.indexOf(name)];
  const heavy = new Set();
  const lines = [`data_${code}`, `_chem_comp.id ${code}`, `_chem_comp.type ${value("_chem_comp.type")}`,
    `_chem_comp.one_letter_code ${value("_chem_comp.one_letter_code")}`, "loop_",
    ...ATOM_COLUMNS.map((c) => `_chem_comp_atom.${c}`)];
  for (const row of atoms.rows) {
    heavy.add(at(atoms, row, "atom_id"));
    lines.push(ATOM_COLUMNS.map((c) => quote(at(atoms, row, c))).join(" "));
  }
  lines.push("loop_", ...BOND_COLUMNS.map((c) => `_chem_comp_bond.${c}`));
  for (const row of bonds.rows) {
    if (!heavy.has(at(bonds, row, "atom_id_1")) || !heavy.has(at(bonds, row, "atom_id_2"))) continue;
    lines.push(BOND_COLUMNS.map((c) => quote(at(bonds, row, c))).join(" "));
  }
  out[code] = lines.join("\n") + "\n";
}
const module = [
  "// GENERATED by tools/gen-standard-components.mjs from the wwPDB CCD (components.cif) - do not edit.",
  "// The standard residues' CCD entries, for a residue the featuriser atomises (rf3's",
  "// atomizeLigandBonded); parse with parseCcdComponent. cuda/featurise/tables.inc carries the same text.",
  "export const STANDARD_COMPONENTS = Object.freeze({",
  ...Object.entries(out).map(([code, cif]) => `  ${JSON.stringify(code)}: ${JSON.stringify(cif)},`),
  "});",
  "",
].join("\n");
writeFileSync(`${repo}shared/af3/featurise/standard-components.js`, module);
console.log(`wrote shared/af3/featurise/standard-components.js (${module.length} bytes, ${CODES.length} components)`);
