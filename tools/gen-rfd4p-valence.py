#!/usr/bin/env python3
"""Generate shared/rfd4p/pipeline/valence.js: RDKit's answer to atomworks' valence probe.

    ~/venv_rfd4p/bin/python tools/gen-rfd4p-valence.py [--check]

atomworks' link chemistry (atomworks/io/utils/link_chemistry.py) decides whether a linked atom
is a legal product by asking RDKit: `_is_valid_rdkit_valence(element, charge, valence)` parses
`[<El>H<valence><charge>]` and accepts it when RDKit sanitises it with no radical electron, and
`_valence_with_neutralization` reads `GetDefaultValence`. Both are pure functions of three small
integers, so the answers are tabulated here from the RDKit atomworks itself runs rather than
re-derived from RDKit's valence rules: for each element, each charge in -4..4, the valences in
0..16 RDKit accepts - or "any" where it accepts all of them (a metal, which RDKit gives no valence
list). An element RDKit does not know (`X`, and `D`, which `[DH1]` does not parse) accepts none.
`--check` fails when stale.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
OUT = REPO / "shared" / "rfd4p" / "pipeline" / "valence.js"
CHARGES = range(-4, 5)
VALENCES = range(0, 17)

HEADER = """// GENERATED by tools/gen-rfd4p-valence.py from RDKit - do not edit.
//
// atomworks' valence probe (`_is_valid_rdkit_valence`): RDKIT_VALENCE[element][charge] lists the
// valences 0..16 for which RDKit parses `[<El>H<valence><charge>]` with no radical, or is "any"
// where it accepts every one; an element or charge not listed accepts none. RDKIT_DEFAULT_VALENCE
// is `GetDefaultValence` (-1 for an element RDKit gives none). Charges -4..4; a probe outside these ranges is refused, not guessed.
"""


def tables() -> dict:
    from rdkit import Chem, RDLogger, rdBase
    from rdkit.Chem import GetPeriodicTable

    RDLogger.DisableLog("rdApp.*")
    pt = GetPeriodicTable()

    def ok(symbol: str, charge: int, valence: int) -> bool:
        spec = f"{charge:+d}" if charge else ""
        with rdBase.BlockLogs():
            mol = Chem.MolFromSmiles(f"[{symbol}H{valence}{spec}]")
        return mol is not None and mol.GetAtomWithIdx(0).GetNumRadicalElectrons() == 0

    valence, default = {}, {}
    for z in range(1, 119):
        symbol = pt.GetElementSymbol(z)
        default[symbol.upper()] = pt.GetDefaultValence(symbol)
        per = {}
        for charge in CHARGES:
            good = [v for v in VALENCES if ok(symbol, charge, v)]
            if good:
                per[str(charge)] = "any" if len(good) == len(VALENCES) else good
        if per:
            valence[symbol.upper()] = per
    return {"valence": valence, "default": default}


def render(t: dict) -> str:
    lines = [HEADER, "export const RDKIT_VALENCE = Object.freeze({"]
    for el, per in t["valence"].items():
        lines.append(f"  {json.dumps(el)}: {json.dumps(per, separators=(',', ':'))},")
    lines += ["});", "", "export const RDKIT_DEFAULT_VALENCE = Object.freeze("
              + json.dumps(t["default"], separators=(",", ":")) + ");"]
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = render(tables())
    if args.check:
        if OUT.exists() and OUT.read_text() == text:
            print(f"{OUT.relative_to(REPO)} is current")
            return 0
        print(f"{OUT.relative_to(REPO)} is STALE - run tools/gen-rfd4p-valence.py", file=sys.stderr)
        return 1
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
