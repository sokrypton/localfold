#!/usr/bin/env python3
"""Generate shared/rfd4p/cath-mapping.js from RFD4-Proteina's own `data/cath_label_mapping.pkl`.

    python3 tools/gen-rfd4p-cath-mapping.py [--upstream ~/RFD4-Proteina] [--check]

🔴 THE INDICES ARE ROWS OF THE CHECKPOINT'S EMBEDDING TABLES, SO THEY ARE NOT OURS TO WRITE.
`FoldEmbeddingSeqFeat` embeds a CATH label as three indices (`embedding_C` 5+1, `embedding_A`
43+1, `embedding_T` 1472+1 rows), and upstream's pipeline turns a label into those indices with
this one pickle. The page's tables were a hand-written subset - 5, 32 and 12 entries - and 26 of
the 32 architecture indices and all 12 topology indices disagreed with it: `3.40.50`, the
fold-conditioned preset's own label, went in as topology 890 where the model was trained on 1056.
Generated, never typed; `--check` fails when the module is stale.
"""
from __future__ import annotations

import argparse
import json
import pickle
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
OUT = REPO / "shared" / "rfd4p" / "cath-mapping.js"

HEADER = """// GENERATED by tools/gen-rfd4p-cath-mapping.py from RFD4-Proteina's
// `data/cath_label_mapping.pkl` - do not edit.
//
// The CATH label -> embedding-row mapping the released checkpoint was trained with: class (C),
// architecture (C.A) and topology (C.A.T), each a row of `FoldEmbeddingSeqFeat`'s tables.
//
// Copyright (c) 2026, Institute for Protein Design, University of Washington. Redistributed under
// RFD4-Proteina's BSD 3-Clause License: redistributions must retain this copyright notice, this
// list of conditions and the following disclaimer. THIS DATA IS PROVIDED BY THE COPYRIGHT HOLDERS
// AND CONTRIBUTORS "AS IS" AND ANY EXPRESS OR IMPLIED WARRANTIES, INCLUDING, BUT NOT LIMITED TO,
// THE IMPLIED WARRANTIES OF MERCHANTABILITY AND FITNESS FOR A PARTICULAR PURPOSE ARE DISCLAIMED.
// Neither the name of the copyright holder nor the names of its contributors may be used to
// endorse or promote products derived from this software without specific prior written
// permission.
"""


def render(mapping: dict) -> str:
    def block(name: str, table: dict) -> str:
        items = sorted(table.items(), key=lambda kv: kv[1])
        body = ",\n".join(f"  {json.dumps(k)}: {int(v)}" for k, v in items)
        return f"export const {name} = Object.freeze({{\n{body},\n}});\n"

    return (HEADER + "\n" + block("CATH_CLASS_MAP", mapping["C"]) + "\n"
            + block("CATH_ARCHITECTURE_MAP", mapping["A"]) + "\n"
            + block("CATH_TOPOLOGY_MAP", mapping["T"]))


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--upstream", default=str(Path.home() / "RFD4-Proteina"))
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    pkl = Path(args.upstream) / "data" / "cath_label_mapping.pkl"
    with open(pkl, "rb") as f:
        mapping = pickle.load(f)
    text = render(mapping)
    if args.check:
        if OUT.exists() and OUT.read_text() == text:
            print(f"{OUT.relative_to(REPO)} is current")
            return 0
        print(f"{OUT.relative_to(REPO)} is STALE - run tools/gen-rfd4p-cath-mapping.py", file=sys.stderr)
        return 1
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(REPO)}: {len(mapping['C'])} classes, {len(mapping['A'])} "
          f"architectures, {len(mapping['T'])} topologies")
    return 0


if __name__ == "__main__":
    sys.exit(main())
